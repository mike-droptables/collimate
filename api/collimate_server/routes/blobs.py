@router.get("/api/config.js")
async def get_runtime_config(request: Request):
    """Introspection endpoint for the runtime UI configuration.

    The bundled UI doesn't fetch this file directly — the index.html
    handler in api/collimate_server/main.py injects the same payload inline. This
    endpoint stays around as a one-line introspection tool: ``curl
    /api/config.js`` returns the values the running server would have
    injected, useful for ops sanity checks and integration tests.

    Default ``apiBase`` is ``./api``: the API beside the UI's document,
    which holds for the app at the site root and for the same app served
    under a prefix (a Collimate server inside a cell, reached at the host
    app's ``/proxy/<channel>/<run>/<port>/``). Operators serving the UI
    apart from its API override via ``COLLIMATE_PUBLIC_API_BASE``.
    """
    payload = runtime_config()
    body = (
        "// Auto-generated by /api/config.js — do not edit.\n"
        f"window.__COLLIMATE_CONFIG__ = {json.dumps(payload)};\n"
    )
    # Short cache so a config change propagates fast on reload but the
    # same response can be reused across subsequent requests in the
    # session. Avoids a hot-path round trip per render.
    return Response(
        content=body,
        media_type="application/javascript",
        headers={"Cache-Control": "max-age=30"},
    )

