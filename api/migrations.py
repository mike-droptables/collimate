def _rewrite_cell_displays(conn: sqlite3.Connection, transform: Callable[[dict], bool]) -> None:
    """Run ``transform`` over every stored cell display (live rows and
    removed cells) and write back each one it reports changed. A display
    that is not a JSON object is dropped."""
    for key, raw in conn.execute("SELECT key, value FROM ui_state WHERE key LIKE 'cell\\_display:%' ESCAPE '\\'").fetchall():
        try:
            display = json.loads(raw)
        except (TypeError, ValueError):
            display = None
        if not isinstance(display, dict):
            conn.execute("DELETE FROM ui_state WHERE key=?", (key,))
        elif transform(display):
            conn.execute("UPDATE ui_state SET value=? WHERE key=?", (json.dumps(display, separators=(",", ":")), key))
    for cell_id, raw in conn.execute("SELECT cell_id, display_json FROM removed_cells WHERE display_json IS NOT NULL").fetchall():
        try:
            display = json.loads(raw)
        except (TypeError, ValueError):
            display = None
        if not isinstance(display, dict):
            conn.execute("UPDATE removed_cells SET display_json=NULL WHERE cell_id=?", (cell_id,))
        elif transform(display):
            conn.execute("UPDATE removed_cells SET display_json=? WHERE cell_id=?",
                         (json.dumps(display, separators=(",", ":")), cell_id))


