def _channel_v14_delta_versions(conn: sqlite3.Connection) -> None:
    """Explicit immutable deltas and transactional accelerators for live heads."""
    conn.execute("""CREATE TABLE cell_file_versions (
        version_id TEXT PRIMARY KEY REFERENCES cells(id),
        parent_version_id TEXT REFERENCES cells(id),
        root_id TEXT NOT NULL REFERENCES cells(id),
        file_count INTEGER NOT NULL DEFAULT 0)""")
    conn.execute("""CREATE TABLE cell_file_heads (
        root_id TEXT PRIMARY KEY REFERENCES cells(id),
        version_id TEXT UNIQUE NOT NULL REFERENCES cells(id))""")
    conn.execute("""CREATE TABLE cell_file_current (
        root_id TEXT REFERENCES cells(id), filepath TEXT, blob_hash TEXT NOT NULL REFERENCES blobs(hash),
        PRIMARY KEY(root_id, filepath))""")
    conn.execute("""CREATE TABLE cell_version_heads (
        cell_id TEXT PRIMARY KEY REFERENCES cells(id), tip_id TEXT NOT NULL REFERENCES cells(id), depth INTEGER NOT NULL)""")
    conn.execute("CREATE INDEX cell_version_heads_tip ON cell_version_heads(tip_id)")
    conn.execute("""INSERT INTO cell_file_versions(version_id,root_id,file_count)
        SELECT c.id,c.id,COUNT(f.filepath) FROM cells c LEFT JOIN cell_files f ON f.cell_id=c.id GROUP BY c.id""")
    conn.execute("""INSERT INTO cell_file_heads SELECT id,id FROM cells c WHERE NOT EXISTS
        (SELECT 1 FROM cell_edges e WHERE e.parent_cell_id=c.id AND e.parent_key='previous_version')""")
    conn.execute("""INSERT INTO cell_file_current SELECT f.cell_id,f.filepath,f.blob_hash
        FROM cell_files f JOIN cell_file_heads h ON h.version_id=f.cell_id WHERE f.blob_hash IS NOT NULL""")
    children = dict(conn.execute("SELECT parent_cell_id,child_cell_id FROM cell_edges WHERE parent_key='previous_version' ORDER BY rowid"))
    nonroots = {r[0] for r in conn.execute("SELECT child_cell_id FROM cell_edges WHERE parent_key='previous_version'")}
    for (root,) in conn.execute("SELECT id FROM cells").fetchall():
        if root in nonroots:
            continue
        tip, seen = root, set()
        while tip in children and tip not in seen:
            seen.add(tip)
            tip = children[tip]
        if tip not in seen:
            conn.execute("INSERT INTO cell_version_heads VALUES (?,?,?)", (root, tip, len(seen)+1))
    # Raw SQL fixtures and independent full-snapshot writers get the same
    # representation. Delta writers set ancestry/count before inserting entries.
    conn.execute("""CREATE TRIGGER cell_file_version_create AFTER INSERT ON cells BEGIN
        INSERT INTO cell_file_versions(version_id,root_id) VALUES(NEW.id,NEW.id); END""")
    for event, expression, owner in (("INSERT", "+1", "NEW"), ("DELETE", "-1", "OLD")):
        conn.execute(f"""CREATE TRIGGER cell_file_count_{event.lower()} AFTER {event} ON cell_files
            WHEN {owner}.blob_hash IS NOT NULL BEGIN
            UPDATE cell_file_versions SET file_count=file_count{expression}
            WHERE version_id={owner}.cell_id AND parent_version_id IS NULL; END""")
    # Edges remain authoritative. Only the ordinary fresh-leaf append can
    # advance cached roots without walking. Any exceptional topology change
    # invalidates them; a writer may rebuild its stable owner from the graph.
    conn.execute("""CREATE TRIGGER cell_version_heads_branch BEFORE INSERT ON cell_edges
        WHEN NEW.parent_key='previous_version' AND (
            NEW.parent_cell_id=NEW.child_cell_id OR EXISTS (
                SELECT 1 FROM cell_version_heads WHERE cell_id=NEW.child_cell_id) OR EXISTS (
                SELECT 1 FROM cell_edges WHERE parent_key='previous_version'
                AND parent_cell_id IN (NEW.parent_cell_id,NEW.child_cell_id)))
        BEGIN DELETE FROM cell_version_heads; END""")
    conn.execute("""CREATE TRIGGER cell_version_heads_append AFTER INSERT ON cell_edges
        WHEN NEW.parent_key='previous_version' BEGIN
        UPDATE cell_version_heads SET tip_id=NEW.child_cell_id,depth=depth+1 WHERE tip_id=NEW.parent_cell_id; END""")
    for event in ("UPDATE", "DELETE"):
        predicate = "OLD.parent_key='previous_version'"
        if event == "UPDATE":
            predicate += " OR NEW.parent_key='previous_version'"
        conn.execute(f"""CREATE TRIGGER cell_version_heads_{event.lower()} AFTER {event} ON cell_edges
            WHEN {predicate} BEGIN DELETE FROM cell_version_heads; END""")


def _channel_v15_cell_moves(conn: sqlite3.Connection) -> None:
    """Lineage between logical cells: one row per (source, result) pair of a
    Duplicate, Merge, Split or Run in new cell. ``op_id`` is the system or
    generator run that performed it and groups the pairs of one operation;
    ``ord`` orders a merge's inputs. ``to_cell`` carries no foreign key: a
    duplicate or a new-cell clone has no ``cells`` row until it is versioned.

    The provenance edges this table replaces become rows and are deleted:
    ``merge_<i>`` (input tip -> merged root) a 'merge' with ``ord`` i,
    ``split_from`` / ``split_restored`` (source tip -> output version) a
    'split', ``branched_from`` (frozen version -> copy) a 'duplicate'. The
    child version's run is the operation, its ``created_at`` the move's; cell
    ids are the chain roots (``previous_version`` walked back)."""
    conn.execute("""CREATE TABLE cell_moves (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        op TEXT NOT NULL CHECK (op IN ('duplicate','merge','split','run_cell')),
        op_id TEXT NOT NULL,
        from_cell TEXT NOT NULL,
        from_version TEXT REFERENCES cells(id),
        to_cell TEXT NOT NULL,
        to_version TEXT,
        ord INTEGER NOT NULL DEFAULT 0,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)""")
    conn.execute("CREATE INDEX idx_cell_moves_from ON cell_moves (from_cell)")
    conn.execute("CREATE INDEX idx_cell_moves_to ON cell_moves (to_cell)")

    def chain_root(version: str) -> str:
        row = conn.execute(
            """WITH RECURSIVE chain(id) AS (
                   SELECT ? UNION
                   SELECT e.parent_cell_id FROM cell_edges e JOIN chain c
                     ON e.child_cell_id=c.id WHERE e.parent_key='previous_version')
               SELECT id FROM chain WHERE NOT EXISTS (SELECT 1 FROM cell_edges e
                   WHERE e.child_cell_id=chain.id AND e.parent_key='previous_version')""",
            (version,),
        ).fetchone()
        return row[0] if row else version  # a corrupt cycle has no root

    edges = conn.execute(
        """SELECT e.parent_cell_id, e.child_cell_id, e.parent_key, c.run_id, c.created_at
           FROM cell_edges e JOIN cells c ON c.id=e.child_cell_id
           WHERE e.parent_key IN ('split_from','split_restored','branched_from')
              OR e.parent_key GLOB 'merge_[0-9]*'
           ORDER BY e.rowid""").fetchall()
    split_ord: dict[str, int] = {}
    for parent, child, key, run_id, created_at in edges:
        if key.startswith("merge_"):
            op, op_id, ord_ = "merge", run_id or child, int(key[6:]) if key[6:].isdigit() else 0
        elif key == "branched_from":
            op, op_id, ord_ = "duplicate", run_id or child, 0
        else:
            op, op_id = "split", run_id or parent
            ord_ = split_ord[op_id] = split_ord.get(op_id, -1) + 1
        conn.execute(
            "INSERT INTO cell_moves (op, op_id, from_cell, from_version, to_cell, to_version, "
            "ord, created_at) VALUES (?,?,?,?,?,?,?,COALESCE(?,CURRENT_TIMESTAMP))",
            (op, op_id, chain_root(parent), parent, chain_root(child), child, ord_, created_at),
        )
    conn.execute("""DELETE FROM cell_edges
        WHERE parent_key IN ('split_from','split_restored','branched_from')
           OR parent_key GLOB 'merge_[0-9]*'""")


