def _merge_capabilities_stacks(channel: dict) -> bool:
    """Fold a raw channel layout's Generators and Renderers stacks (stack
    types 'generator' and 'renderer') into one Capabilities stack, in place;
    True when the channel had any.

    The stack keeps the id and fields of the first Renderers stack (it holds
    the built-in cards), else of the first of them, so the cards stay at its
    head. Its cells are the built-in cards, then every other cell of those
    stacks in layout order (main stacks, then navigation stacks), each id
    once. It stands where the first of them stood on the board, else at the
    end of the navigation stacks. A board selection of one of them moves to
    the merged stack when that is on the board, else to the first board
    stack; a navigation selection of one of them clears, unless it names the
    merged stack and that stays in navigation."""
    def rows(holder: dict, key: str) -> list:
        value = holder.get(key)
        return value if isinstance(value, list) else []
    main, nav = rows(channel, "main_stacks"), rows(channel, "nav_stacks")
    stacks = [stack for stack in [*main, *nav]
              if isinstance(stack, dict) and stack.get("stack_type") in ("generator", "renderer")]
    if not stacks:
        return False
    folded = {id(stack) for stack in stacks}
    survivor = next((stack for stack in stacks if stack.get("stack_type") == "renderer"), stacks[0])
    cells: list = []
    seen: set = set()
    for builtin in (True, False):
        for stack in stacks:
            for cell in rows(stack, "cells"):
                if not isinstance(cell, dict) or bool(cell.get("builtin")) is not builtin or cell.get("id") in seen:
                    continue
                seen.add(cell.get("id"))
                cells.append(cell)
    merged = {**survivor, "name": "Capabilities", "stack_type": "capabilities", "cells": cells}
    kept_main = [stack for stack in main if id(stack) not in folded]
    kept_nav = [stack for stack in nav if id(stack) not in folded]
    first_main = next((i for i, stack in enumerate(main) if id(stack) in folded), None)
    on_main = first_main is not None
    if on_main:
        kept_main.insert(first_main, merged)
    else:
        kept_nav.append(merged)
    channel["main_stacks"], channel["nav_stacks"] = kept_main, kept_nav
    folded_ids = {stack.get("id") for stack in stacks}
    if channel.get("main_selection_id") in folded_ids:
        first = merged if on_main else (kept_main[0] if kept_main else None)
        channel["main_selection_id"] = first.get("id") if isinstance(first, dict) else None
    nav_kept = not on_main and channel.get("nav_selection_id") == merged.get("id")
    if channel.get("nav_selection_id") in folded_ids and not nav_kept:
        channel["nav_selection_id"] = None
    return True


def _global_v9_capabilities_stack(conn: sqlite3.Connection) -> None:
    """Every channel's Generators and Renderers stacks become its one
    Capabilities stack (``_merge_capabilities_stacks``), on the raw layout
    JSON. A missing or unparsable row is left for startup's quarantine."""
    row = conn.execute("SELECT value FROM ui_state WHERE key='app_state'").fetchone()
    if row is None:
        return
    try:
        data = json.loads(row[0])
    except (TypeError, ValueError):
        return
    if not isinstance(data, dict) or not isinstance(data.get("channels"), list):
        return
    merged = [_merge_capabilities_stacks(channel) for channel in data["channels"] if isinstance(channel, dict)]
    if any(merged):
        conn.execute("UPDATE ui_state SET value=? WHERE key='app_state'",
                     (json.dumps(data, sort_keys=True, separators=(",", ":"), allow_nan=False),))


