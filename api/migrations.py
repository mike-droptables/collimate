def _global_v3_cas_layout(conn: sqlite3.Connection) -> None:
    """Convert the one pre-P2 inline layout; runtime readers use CAS only."""
    from models import AppState
    from cell_commits import file_content_hash

    row = conn.execute("SELECT value FROM ui_state WHERE key='app_state'").fetchone()
    if row is None:
        return
    try:
        data = json.loads(row[0])
        if (not isinstance(data, dict) or not isinstance(data.get("channels"), list)
                or data.get("storage_format") is not None):
            return
        layout = AppState.model_validate(data)
    except (TypeError, ValueError):
        # Preserve malformed bytes for startup's established quarantine policy.
        return
    snapshot = layout.model_dump(mode="json")
    snapshot["storage_format"] = "cas-layout-v1"
    for channel_data, channel in zip(snapshot["channels"], layout.channels):
        for kind in ("main_stacks", "nav_stacks"):
            for stack_data, stack in zip(channel_data[kind], getattr(channel, kind)):
                for cell_data, cell in zip(stack_data["cells"], stack.cells):
                    for file_data, file in zip(cell_data["files"], cell.files):
                        file_data.pop("content", None)
                        file_data["content_hash"] = file_content_hash(file)
    conn.execute("UPDATE ui_state SET value=? WHERE key='app_state'", (json.dumps(snapshot),))


