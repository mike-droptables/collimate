def _channel_v23_typed_history(conn: sqlite3.Connection) -> None:
    """One-time type conversion; subsequent history writers supply exact types."""
    from cas import require_blob
    from models import language_for
    from versions import find_tip, tip_file_map
    for table in ('cell_files', 'cell_file_current'):
        conn.execute(f"ALTER TABLE {table} ADD COLUMN encoding TEXT CHECK(encoding IS NULL OR encoding IN ('utf-8','binary'))")
        conn.execute(f"ALTER TABLE {table} ADD COLUMN language TEXT")
    types = {}
    for version, path, digest in conn.execute('SELECT cell_id,filepath,blob_hash FROM cell_files').fetchall():
        if digest is None:
            continue
        if digest not in types:
            raw = require_blob(digest)
            try:
                raw.decode('utf-8')
                types[digest] = 'utf-8'
            except UnicodeDecodeError:
                types[digest] = 'binary'
        encoding = types[digest]
        conn.execute('UPDATE cell_files SET encoding=?,language=? WHERE cell_id=? AND filepath=?',
                     (encoding, 'binary' if encoding == 'binary' else language_for(path), version, path))
    # Removed records captured type choices for their exact retained tip.
    # Add a typed delta there rather than changing an inherited ancestor.
    for cell_id, binary_json in conn.execute('SELECT cell_id,binary_paths_json FROM removed_cells').fetchall():
        tip = find_tip(conn, cell_id)
        binary_paths = set(json.loads(binary_json))
        for path, digest in tip_file_map(conn, tip).items():
            encoding = 'binary' if path in binary_paths else 'utf-8'
            raw = require_blob(digest)
            if encoding == 'utf-8':
                raw.decode('utf-8')
            conn.execute('INSERT INTO cell_files(cell_id,filepath,blob_hash,encoding,language) VALUES (?,?,?,?,?) '
                         'ON CONFLICT(cell_id,filepath) DO UPDATE SET encoding=excluded.encoding,language=excluded.language',
                         (tip,path,digest,encoding,'binary' if encoding == 'binary' else language_for(path)))
    for root, head in conn.execute('SELECT root_id,version_id FROM cell_file_heads').fetchall():
        resolved, version, seen = {}, head, set()
        while version is not None:
            if version in seen:
                raise ValueError('Cyclic historical file ancestry during type conversion')
            seen.add(version)
            row = conn.execute('SELECT parent_version_id FROM cell_file_versions WHERE version_id=?', (version,)).fetchone()
            if row is None:
                raise ValueError('Missing historical file ancestry during type conversion')
            for path,digest,encoding,language in conn.execute('SELECT filepath,blob_hash,encoding,language FROM cell_files WHERE cell_id=?', (version,)):
                resolved.setdefault(path,(digest,encoding,language))
            version = row[0]
        conn.execute('DELETE FROM cell_file_current WHERE root_id=?', (root,))
        conn.executemany('INSERT INTO cell_file_current(root_id,filepath,blob_hash,encoding,language) VALUES (?,?,?,?,?)',
                         [(root,path,*entry) for path,entry in resolved.items() if entry[0] is not None])
    for event in ('INSERT', 'UPDATE OF blob_hash,encoding,language'):
        suffix = 'insert' if event == 'INSERT' else 'update'
        conn.execute(f"""CREATE TRIGGER cell_files_typed_{suffix} BEFORE {event} ON cell_files
            WHEN (NEW.blob_hash IS NOT NULL AND (NEW.encoding IS NULL OR NEW.language IS NULL))
              OR (NEW.blob_hash IS NULL AND (NEW.encoding IS NOT NULL OR NEW.language IS NOT NULL))
            BEGIN SELECT RAISE(ABORT,'historical file entry requires explicit type'); END""")
        conn.execute(f"""CREATE TRIGGER cell_file_current_typed_{suffix} BEFORE {event} ON cell_file_current
            WHEN NEW.encoding IS NULL OR NEW.language IS NULL
            BEGIN SELECT RAISE(ABORT,'historical file index requires explicit type'); END""")


