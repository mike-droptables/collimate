def _strip_tab_kind(node, kind: str) -> bool:
    """Remove the tabs of ``kind`` from a display tree in place; True when
    any went. A leaf whose active tab went selects the surviving tab nearest
    it; a leaf left with no tabs gets one empty tab, as the app gives a leaf
    whose last tab closes."""
    import uuid
    if not isinstance(node, dict):
        return False
    if node.get("type") == "split":
        changed = False
        for child in node.get("children", []) if isinstance(node.get("children"), list) else []:
            changed = _strip_tab_kind(child, kind) or changed
        return changed
    tabs = node.get("tabs")
    if not isinstance(tabs, list):
        return False
    kept = [tab for tab in tabs if not (isinstance(tab, dict) and tab.get("kind") == kind)]
    if len(kept) == len(tabs):
        return False
    active = node.get("activeTabId")
    if not kept:
        kept = [{"id": "t-" + uuid.uuid4().hex, "kind": "empty"}]
        active = kept[0]["id"]
    elif not any(isinstance(tab, dict) and tab.get("id") == active for tab in kept):
        at = next((i for i, tab in enumerate(tabs) if isinstance(tab, dict) and tab.get("id") == active), len(tabs))
        after = [tab for tab in tabs[at:] if tab in kept]
        before = [tab for tab in tabs[:at] if tab in kept]
        active = (after[0] if after else before[-1]).get("id")
    node["tabs"] = kept
    node["activeTabId"] = active
    return True


