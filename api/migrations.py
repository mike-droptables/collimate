def upgrade_global_db(conn: sqlite3.Connection) -> list[int]:
    """Apply every global-DB migration newer than the connection's
    current head. Returns the list of versions applied. An app database
    that stopped before version 8 is refused: its earlier migrations read
    layouts this build's models no longer validate."""
    _ensure_version_table(conn)
    applied = _applied_versions(conn)
    if applied and max(applied) < 8:
        raise RuntimeError(
            "This .collimate holds an app database older than global schema 8; "
            "this build does not upgrade it. Move it aside and start fresh."
        )
    return apply(conn, GLOBAL_MIGRATIONS)
