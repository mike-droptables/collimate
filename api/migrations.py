def _channel_v19_file_revisions(conn: sqlite3.Connection) -> None:
    """Accepted working revisions and immutable operation/conflict provenance."""
    conn.execute("""CREATE TABLE file_revisions (
        cell_id TEXT NOT NULL,path TEXT NOT NULL,revision INTEGER NOT NULL,
        base_revision INTEGER NOT NULL,body_hash TEXT,deleted INTEGER NOT NULL,
        language TEXT NOT NULL,encoding TEXT NOT NULL,writer_id TEXT NOT NULL,
        edit_seq INTEGER NOT NULL,operation_id TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY(cell_id,path,revision),CHECK((deleted=1 AND body_hash IS NULL) OR (deleted=0 AND body_hash IS NOT NULL)))""")
    conn.execute("CREATE INDEX file_revisions_writer ON file_revisions(cell_id,path,writer_id,edit_seq)")
    conn.execute("""CREATE TABLE working_files (cell_id TEXT NOT NULL,path TEXT NOT NULL,revision INTEGER NOT NULL,
        PRIMARY KEY(cell_id,path),FOREIGN KEY(cell_id,path,revision) REFERENCES file_revisions(cell_id,path,revision))""")
    conn.execute("""CREATE TABLE file_operations (operation_id TEXT PRIMARY KEY,cell_id TEXT NOT NULL,
        request_digest TEXT NOT NULL,result_json TEXT NOT NULL)""")
    conn.execute("""CREATE TABLE file_conflicts (conflict_id TEXT PRIMARY KEY,operation_id TEXT NOT NULL,
        cell_id TEXT NOT NULL,path TEXT NOT NULL,base_revision INTEGER NOT NULL,current_revision INTEGER NOT NULL,
        candidate_revision INTEGER NOT NULL,resolution_operation_id TEXT,
        FOREIGN KEY(cell_id,path,candidate_revision) REFERENCES file_revisions(cell_id,path,revision))""")
    conn.execute("CREATE INDEX file_conflicts_cell ON file_conflicts(cell_id,resolution_operation_id)")
    # Import accepted historical tips and outstanding drafts once. Runtime has
    # only working_files; this is a schema conversion, not read precedence.
    from versions import tip_file_map
    from cas import store_bytes, read_blob
    from models import language_for
    roots = {r[0]: r[1] for r in conn.execute("SELECT cell_id,tip_id FROM cell_version_heads")}
    roots.update((r[0],r[0]) for r in conn.execute("SELECT id FROM cells WHERE id NOT IN (SELECT child_cell_id FROM cell_edges WHERE parent_key='previous_version')") if r[0] not in roots)
    drafts = conn.execute("SELECT cell_id,filepath,content_text,blob_hash FROM cell_drafts").fetchall()
    ids = roots.keys() | {r['cell_id'] for r in drafts}
    for cid in ids:
        files: dict[str, tuple[str | None, bool, str | None]] = {
            p:(h,False,None) for p,h in tip_file_map(conn,roots.get(cid,cid)).items()}
        for row in drafts:
            if row['cell_id'] != cid:
                continue
            text = row['content_text']
            files[row['filepath']] = (store_bytes(text.encode('utf-8')) if text is not None else row['blob_hash'],
                                      text is None and row['blob_hash'] is None, 'utf-8' if text is not None else None)
        for path,(digest,deleted,encoding) in files.items():
            if not deleted and encoding is None:
                raw = read_blob(digest)
                if raw is None:
                    raise OSError('Missing file body during migration')
                try:
                    raw.decode('utf-8')
                    encoding = 'utf-8'
                except UnicodeDecodeError:
                    encoding = 'binary'
            conn.execute("INSERT INTO file_revisions(cell_id,path,revision,base_revision,body_hash,deleted,language,encoding,writer_id,edit_seq,operation_id) VALUES (?,?,1,0,?,?,?,?,?,1,?)",
                         (cid,path,digest,deleted,language_for(path),encoding or 'utf-8','host:migration','migration:' + cid))
            conn.execute("INSERT INTO working_files VALUES (?,?,1)",(cid,path))


