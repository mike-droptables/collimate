    """Give a stored display's files pane its dock side ('left' when it has
    none) and its width and height (null, the app default, when missing);
    True when anything changed."""
    pane = display.get("filesPane")
    if not isinstance(pane, dict):
        return False
    changed = False
    for key, value in (("side", "left"), ("width", None), ("height", None)):
        if key not in pane:
            pane[key] = value
            changed = True
    return changed


