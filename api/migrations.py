def _drop_retired_state_fields(conn: sqlite3.Connection) -> None:
    """Discard retired settings and stack fields in persisted UI documents."""
    for key, raw in conn.execute(
        "SELECT key, value FROM ui_state WHERE key IN ('app_state', 'channel_settings')"
    ).fetchall():
        try:
            doc = json.loads(raw)
        except (TypeError, ValueError):
            continue
        if not isinstance(doc, dict):
            continue
        if key == "channel_settings":
            doc.pop("pins", None)
        else:
            channels = doc.get("channels", [])
            if not isinstance(channels, list):
                continue
            for channel in channels:
                if not isinstance(channel, dict):
                    continue
                for field in ("main_stacks", "nav_stacks"):
                    stacks = channel.get(field, [])
                    if not isinstance(stacks, list):
                        continue
                    for stack in stacks:
                        if isinstance(stack, dict):
                            stack.pop("width", None)
                            stack.pop("prev_width", None)
        conn.execute("UPDATE ui_state SET value=? WHERE key=?", (json.dumps(doc), key))


