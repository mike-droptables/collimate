def _global_v6_sql_layout(conn: sqlite3.Connection) -> None:
    """Preserve legacy layout-only roots once, then retire all duplicate body maps."""
    row = conn.execute("SELECT value FROM ui_state WHERE key='app_state'").fetchone()
    if row is None:
        return
    from models import AppState
    try:
        data = json.loads(row[0])
        if not isinstance(data, dict) or not isinstance(data.get('channels'), list):
            return  # Startup quarantines malformed layouts without touching channels.
        layout = AppState.model_validate(data)
    except (TypeError, ValueError):
        return
    from database import migrate_channel_database_identities, get_db_connection
    from persistence import initialize_files, snapshot_files
    from cas import require_blob
    from genesis import snapshot_app_state
    _require_layout_channel_ids(data)
    migrate_channel_database_identities(layout.channels)
    for source_channel, channel in zip(data['channels'], layout.channels):
        channel_conn = get_db_connection(str(channel.id))
        try:
            for kind in ('main_stacks', 'nav_stacks'):
                for source_stack in source_channel.get(kind, []):
                    for cell in source_stack.get('cells', []):
                        if snapshot_files(channel_conn, cell['id'], include_deleted=True):
                            continue
                        entries = []
                        for file in cell.get('files', []):
                            digest = file.get('content_hash') or file.get('blob_hash')
                            if digest is None:
                                raise ValueError('Legacy layout file lacks a durable body reference')
                            raw = require_blob(digest)
                            encoding = 'binary' if file.get('blob_hash') else 'utf-8'
                            if encoding == 'utf-8':
                                raw.decode('utf-8')
                            entries.append(dict(path=file['name'],body_hash=digest,encoding=encoding,language=file.get('language')))
                        initialize_files(channel_conn, cell['id'], entries)
            channel_conn.commit()
        except BaseException:
            channel_conn.rollback()
            raise
        finally:
            channel_conn.close()
    conn.execute("UPDATE ui_state SET value=? WHERE key='app_state'", (json.dumps(snapshot_app_state(layout)),))


