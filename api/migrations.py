def _channel_v5_run_nodes(conn: sqlite3.Connection) -> None:
    """Separate generator runs from system checkpoints, forks and merges.

    ``runs.target_cell_id`` is the durable run-to-cell link, including runs
    that emit no version. ``run_artifacts`` owns kickoff configuration and
    finalized logs; their bytes live in CAS rather than cell file rows.
    ``runner_id IS NOT NULL`` identifies generator runs during the backfill.
    The obsolete reserved-file rows are removed and their blobs become
    eligible for normal reference-counted garbage collection.
    """
    for ddl in (
        "ALTER TABLE runs ADD COLUMN kind TEXT NOT NULL DEFAULT 'system'",
        "ALTER TABLE runs ADD COLUMN target_cell_id TEXT",
    ):
        try:
            conn.execute(ddl)
        except sqlite3.OperationalError as e:
            if "duplicate column" not in str(e).lower():
                raise
    conn.execute("""
        CREATE TABLE IF NOT EXISTS run_artifacts (
            run_id     TEXT NOT NULL REFERENCES runs(id),
            category   TEXT NOT NULL CHECK (category IN ('config','log')),
            filepath   TEXT NOT NULL,
            blob_hash  TEXT NOT NULL REFERENCES blobs(hash),
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (run_id, category, filepath)
        )
    """)
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_run_artifacts_blob "
        "ON run_artifacts (blob_hash)"
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_runs_target_cell "
        "ON runs (target_cell_id) WHERE target_cell_id IS NOT NULL"
    )
    conn.execute("UPDATE runs SET kind='generator' WHERE runner_id IS NOT NULL")
    # Backfill the run→cell link for legacy generator runs, or /history
    # renders every pre-existing cell as one anonymous files node (a run
    # node needs kind AND target). A legacy run's TARGET rows are the ones
    # it emitted (source_type generator/chat) — the JIT flush also minted
    # manual_edit/genesis rows on the generator/runner SOURCE cells under
    # the same run_id, which must not win. Walk from an emitted row back
    # to the chain root (= the visible canvas id). A run with no emitted
    # rows (crashed, or a legacy one-emit run collapsed onto the pre-run
    # row) stays NULL and simply has no node — accepted for legacy data.
    gen_runs = conn.execute(
        "SELECT id FROM runs WHERE kind='generator' AND target_cell_id IS NULL"
    ).fetchall()
    for run_row in gen_runs:
        run_id = run_row[0]
        emitted = conn.execute(
            "SELECT id FROM cells WHERE run_id=? "
            "AND source_type IN ('generator', 'chat') "
            "ORDER BY sequence_num LIMIT 1",
            (run_id,),
        ).fetchone()
        if emitted is None:
            continue
        cur = emitted[0]
        seen = {cur}
        while True:
            parent = conn.execute(
                "SELECT parent_cell_id FROM cell_edges "
                "WHERE child_cell_id=? AND parent_key='previous_version' LIMIT 1",
                (cur,),
            ).fetchone()
            if parent is None or parent[0] in seen:
                break
            cur = parent[0]
            seen.add(cur)
        conn.execute(
            "UPDATE runs SET target_cell_id=? WHERE id=?", (cur, run_id),
        )
    conn.execute("DELETE FROM cell_files WHERE filepath LIKE '.collreserved/%'")


