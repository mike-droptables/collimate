"""Per-database schema migration framework.

Why not Alembic? Alembic is the right answer when the schema is owned
by a single database and a project full of contributors needs structured
revision review. Here we have:

  * Two database shapes — the global ``app.db`` and one per channel.
  * A single-tenant deployment where rollback, multi-engine support, and
    revision-graph metadata buy nothing.
  * A schema small enough that a flat list of migration functions is more
    readable than an autogenerated revision file per change.

This module gives the same load-bearing properties Alembic gives:

  * **Version visibility.** ``schema_migrations`` rows record every
    migration that ran, with timestamp.
  * **Ordered application.** Migrations are an explicit list with
    integer versions; the driver applies whatever's missing.
  * **Idempotent on re-run.** Re-opening a fully-migrated DB is a single
    SELECT.
  * **Per-DB tracking.** Each channel DB carries its own
    ``schema_migrations`` table — a freshly created channel runs from
    scratch; an old channel catches up as needed.

To add a migration: append ``(N, _channel_migration_<short_name>)`` to
``CHANNEL_MIGRATIONS``. Each function takes a sqlite3.Connection,
performs DDL/data fixes, and is responsible for being idempotent within
a transaction. The driver wraps each migration in BEGIN/COMMIT.

A migration that's already a no-op on re-run (e.g. ``CREATE TABLE IF NOT
EXISTS``, ``ALTER TABLE`` wrapped in ``OperationalError`` swallow) keeps
the existing pattern. The version row is what decides whether it runs.
"""

from __future__ import annotations

import json
import logging
import sqlite3
from datetime import datetime
from typing import Callable, Iterable

logger = logging.getLogger(__name__)


# Each migration is a tuple of (version, name, function). Versions must
# be strictly increasing. Inserting a migration in the middle (e.g. v3.5)
# is not supported — append a new highest version instead.
Migration = tuple[int, str, Callable[[sqlite3.Connection], None]]


def _ensure_version_table(conn: sqlite3.Connection) -> None:
    conn.execute("""
        CREATE TABLE IF NOT EXISTS schema_migrations (
            version INTEGER PRIMARY KEY,
            name TEXT NOT NULL,
            applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
    """)
    conn.commit()


def _applied_versions(conn: sqlite3.Connection) -> set[int]:
    rows = conn.execute("SELECT version FROM schema_migrations").fetchall()
    return {row[0] for row in rows}


def apply(conn: sqlite3.Connection, migrations: Iterable[Migration]) -> list[int]:
    """Apply every migration whose version isn't already recorded.

    Returns the list of versions actually applied this call (empty when
    the DB was already at head). Each migration runs inside a separate
    transaction so a failure leaves earlier migrations committed and
    raises, so re-running picks up where the failure occurred.
    """
    _ensure_version_table(conn)
    applied = _applied_versions(conn)
    ran: list[int] = []

    for version, name, func in sorted(migrations, key=lambda m: m[0]):
        if version in applied:
            continue
        # Explicit BEGIN — legacy-mode sqlite3 runs DDL in autocommit
        # unless a transaction is open, so without it a half-applied
        # migration would leave the CREATE/ALTER committed without a
        # schema_migrations row. The BEGIN makes the DDL, the data fixes
        # and the version row one atomic unit. Migrations must therefore
        # use conn.execute/executemany, never conn.executescript, which
        # COMMITs the pending transaction first. IMMEDIATE takes the write
        # lock up front, so a second connection opening the same new db
        # (the GC reads a channel db while its creation is in flight) waits
        # here, then finds the version recorded and skips it.
        conn.execute("BEGIN IMMEDIATE")
        if version in _applied_versions(conn):
            conn.rollback()
            continue
        logger.info("schema migration %d (%s) — applying", version, name)
        try:
            func(conn)
            conn.execute(
                "INSERT INTO schema_migrations (version, name) VALUES (?, ?)",
                (version, name),
            )
            conn.commit()
            ran.append(version)
        except Exception:
            conn.rollback()
            logger.exception("schema migration %d (%s) failed", version, name)
            raise

    return ran


