def _channel_v17_removed_cells(conn: sqlite3.Connection) -> None:
    """Cells off the canvas whose history is kept for the Removed shelf.

    Moves the ``ui_state['removed_cells']`` JSON document into rows and
    deletes the key. Its entries were written by Remove only, from stacks of
    unknown size: ``reason`` 'removed', ``stack_cell_count`` 1. Timestamps
    become UTC ISO with offset (the layout's were naive local time)."""
    from time_wire import iso, now_iso

    conn.execute("""CREATE TABLE removed_cells (
        cell_id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        icon TEXT,
        stack_name TEXT,
        stack_type TEXT,
        stack_cell_count INTEGER NOT NULL,
        cell_created_at TIMESTAMP,
        cell_updated_at TIMESTAMP,
        removed_at TIMESTAMP NOT NULL,
        pinned TEXT,
        metadata_json TEXT NOT NULL,
        binary_paths_json TEXT NOT NULL,
        reason TEXT NOT NULL CHECK (reason IN ('removed','merged','split')))""")
    row = conn.execute("SELECT value FROM ui_state WHERE key='removed_cells'").fetchone()
    conn.execute("DELETE FROM ui_state WHERE key='removed_cells'")
    try:
        document = json.loads(row[0]) if row else {}
    except (TypeError, ValueError):
        document = {}
    if not isinstance(document, dict):
        return

    def stamp(value):
        # Layout dumps are naive local ISO; removed_at carries its offset.
        if not isinstance(value, str) or not value:
            return None
        try:
            return iso(datetime.fromisoformat(value))
        except ValueError:
            return None

    for cell_id, entry in document.items():
        if not isinstance(entry, dict):
            continue
        cell = entry.get("cell")
        if not isinstance(cell, dict):
            cell = {}
        binary_paths = entry.get("binary_paths")
        created, updated = stamp(cell.get("created_at")), stamp(cell.get("updated_at"))
        conn.execute(
            "INSERT OR REPLACE INTO removed_cells (cell_id, name, icon, stack_name, stack_type, "
            "stack_cell_count, cell_created_at, cell_updated_at, removed_at, pinned, "
            "metadata_json, binary_paths_json, reason) VALUES (?,?,?,?,?,1,?,?,?,?,?,?,'removed')",
            (str(cell_id), str(cell.get("name") or "Cell"), cell.get("icon"),
             entry.get("stack_name"), entry.get("stack_type"), created, updated,
             stamp(entry.get("removed_at")) or updated or now_iso(), cell.get("pinned"),
             json.dumps(cell),
             json.dumps([p for p in binary_paths if isinstance(p, str)] if isinstance(binary_paths, list) else [])),
        )


