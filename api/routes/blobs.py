class _PinnedFileResponse(FileResponse):
    def __init__(self, path: str, *, digest: str, **kwargs):
        super().__init__(path, **kwargs)
        self._digest = digest

    async def __call__(self, scope, receive, send):
        from cas import pin_blobs
        lease = pin_blobs([self._digest])
        entry = asyncio.create_task(asyncio.to_thread(lease.__enter__))
        try:
            await asyncio.shield(entry)
        except asyncio.CancelledError:
            await entry
            lease.__exit__(None, None, None)
            raise
        except FileNotFoundError:
            await Response(status_code=404)(scope, receive, send)
            return
        try:
            await super().__call__(scope, receive, send)
        finally:
            lease.__exit__(None, None, None)


def _cas_response(digest, **kwargs):
    return _PinnedFileResponse(blob_path(digest), digest=digest, **kwargs)


