@router.post("/api/blob")
async def upload_blob(request: Request):
    """Store a raw byte payload in the CAS and return its hash.

    The caller submits the returned ``blob_hash`` in a conditional file
    mutation. Accepted file revisions retain its bytes immediately; a
    checkpoint independently groups those references into history.
    """
    from cas import MAX_BLOB_BYTES, hash_and_store_bytes

    raw = await request.body()
    if len(raw) > MAX_BLOB_BYTES:
        raise HTTPException(413, f"Blob exceeds the {MAX_BLOB_BYTES // (1024 * 1024)} MB cap")
    try:
        blob_hash = await asyncio.to_thread(hash_and_store_bytes, raw)
    except OSError as exc:
        raise HTTPException(507, "Could not durably store blob") from exc
    return {"blob_hash": blob_hash, "size": len(raw)}


_ABORTED = object()


async def consume_request_body(request: Request, consume):
    """Run ``consume(chunks)`` on a worker thread over the request body.

    ``chunks`` is a blocking iterator fed from ``request.stream()`` through a
    bounded queue, so neither side ever holds more than a few chunks. A client
    disconnect makes the iterator raise ``OSError`` inside ``consume``; an
    exception from ``consume`` stops the read and propagates here.
    """
    pending: queue.Queue = queue.Queue(maxsize=8)

    def chunks():
        while True:
            item = pending.get()
            if item is None:
                return
            if item is _ABORTED:
                raise OSError("Upload aborted by the client")
            yield item

    worker = asyncio.ensure_future(asyncio.to_thread(consume, chunks()))

    async def offer(item) -> bool:
        while not worker.done():
            try:
                pending.put_nowait(item)
                return True
            except queue.Full:
                try:
                    await asyncio.to_thread(pending.put, item, True, 0.1)
                    return True
                except queue.Full:
                    continue
        return False

    try:
        async for chunk in request.stream():
            if chunk and not await offer(chunk):
                break
        await offer(None)
    except BaseException:
        await offer(_ABORTED)
        try:
            await worker
        except Exception:
            pass
        raise
    return await worker


@router.post("/api/blob/stream")
async def upload_blob_stream(request: Request):
    """Stream a raw request body of any type into the CAS.

    The body is written to disk as it arrives (the route is exempt from the
    buffered-body cap) and capped at ``IMPORT_MAX_FILE_BYTES``. The answer
    carries the server's text/binary sniff, which the import commit applies
    again on its own.
    """
    from cas import (INCOMING_DIR, IMPORT_MAX_FILE_BYTES, BlobTooLarge, blob_path, encoding_for,
                     remove_stale_uploads, store_stream)

    declared = request.headers.get("content-length")
    if declared and declared.isdigit() and int(declared) > IMPORT_MAX_FILE_BYTES:
        raise HTTPException(413, f"File exceeds the {IMPORT_MAX_FILE_BYTES}-byte import cap")

    def store(chunks):
        remove_stale_uploads(INCOMING_DIR, ".part")
        blob_hash, size = store_stream(chunks, max_bytes=IMPORT_MAX_FILE_BYTES)
        return blob_hash, size, encoding_for(blob_path(blob_hash))

    try:
        blob_hash, size, encoding = await consume_request_body(request, store)
    except BlobTooLarge as exc:
        raise HTTPException(413, f"File exceeds the {exc.limit}-byte import cap") from exc
    except OSError as exc:
        raise HTTPException(507, "Could not durably store blob") from exc
    return {"blob_hash": blob_hash, "size": size, "encoding": encoding}


def _refuse_service_worker_script(request: Request) -> None:
    """403 a service worker's script fetch (``Service-Worker: script``). A
    worker's scope is its script's folder and it outlives the page that
    registered it, so a cell file or blob registered as one (from a proxied
    page, which shares the app origin) would answer every later request under
    that folder with responses of its own making, the CSP sandbox of
    ``_cell_file_headers`` included."""
    if request.headers.get("service-worker", "").strip().lower() == "script":
        raise HTTPException(403, "A cell file or blob cannot be a service worker script")


@router.get("/api/blob/{blob_hash}")
async def get_blob(blob_hash: str, request: Request):
    """Serve a file from the CAS by its SHA-256 hex digest."""
    _refuse_service_worker_script(request)
    if not is_cas_hash(blob_hash):
        raise HTTPException(400, "Invalid hash format — must be 64 hex chars")

    cas_path = blob_path(blob_hash)

    # Stat runs on a worker thread; FileResponse streams the bytes off
    # disk and honours Range requests (media seeking).
    if not await asyncio.to_thread(os.path.isfile, cas_path):
        raise HTTPException(404, "Blob not found in CAS")

    # CAS paths carry no extension, so there is no type to guess, and
    # ``nosniff`` keeps a browser from guessing one (HTML among them).
    return _cas_response(
        blob_hash,
        media_type="application/octet-stream",
        headers={
            "Cache-Control": "public, max-age=31536000, immutable",
            "X-Content-Type-Options": "nosniff",
        },
    )


# Cell files are written by runs and agents, so none may run as a document
# with the app origin's reach. Nothing is type-sniffed, and a type a browser
# runs as a document (HTML, XHTML, SVG, XML, XSL) is served under a CSP
# sandbox: its scripts still run, but in an opaque origin, with no access to
# the app's API, cookies or storage. The html renderer's preview (a
# ``srcDoc`` frame without ``allow-same-origin``) already runs a page that
# way; the header covers the file URL opened on its own.
_SANDBOXED_DOCUMENT_TYPES = frozenset({"text/html", "text/xml", "application/xml", "text/xsl"})
_CELL_FILE_CSP = "sandbox allow-scripts allow-popups allow-forms"


def _cell_file_headers(media_type: str) -> dict[str, str]:
    """The response headers of a served cell file: ``no-store`` (the URL
    names a cell, not content), ``nosniff``, and the CSP sandbox for an
    active document type (see ``_SANDBOXED_DOCUMENT_TYPES``)."""
    headers = {"Cache-Control": "no-store", "X-Content-Type-Options": "nosniff"}
    kind = media_type.split(";", 1)[0].strip().lower()
    if kind in _SANDBOXED_DOCUMENT_TYPES or kind.endswith("+xml"):
        headers["Content-Security-Policy"] = _CELL_FILE_CSP
    return headers


def _accepted_body_response(raw: bytes, request: Request, media_type: str, headers: dict[str, str]):
    """Apply byte ranges to the already verified, revision-pinned body."""
    headers = dict(headers, **{"Accept-Ranges": "bytes"})
    http_range = request.headers.get("range")
    if_range = request.headers.get("if-range")
    if not http_range or (if_range and if_range != headers.get("ETag")):
        return Response(raw, media_type=media_type, headers=headers)
    try:
        ranges = FileResponse._parse_range_header(http_range, len(raw))
    except MalformedRangeHeader as exc:
        return Response(str(exc), status_code=400, headers=headers)
    except RangeNotSatisfiable:
        headers["Content-Range"] = f"bytes */{len(raw)}"
        return Response(status_code=416, headers=headers)
    if not ranges:
        return Response(raw, media_type=media_type, headers=headers)
    if len(ranges) == 1:
        start, end = ranges[0]
        headers["Content-Range"] = f"bytes {start}-{end - 1}/{len(raw)}"
        return Response(raw[start:end], status_code=206, media_type=media_type, headers=headers)
    from secrets import token_hex
    boundary = token_hex(13)
    body = b"".join(
        (f"--{boundary}\r\nContent-Type: {media_type}\r\n"
         f"Content-Range: bytes {start}-{end - 1}/{len(raw)}\r\n\r\n").encode("latin-1")
        + raw[start:end] + b"\r\n" for start, end in ranges
    )
    body += f"--{boundary}--".encode("latin-1")
    return Response(body, status_code=206, media_type=f"multipart/byteranges; boundary={boundary}", headers=headers)


@router.get("/api/channels/{channel}/cells/{cell_id}/file-paths")
def renderer_file_paths(channel: str, cell_id: str, version_id: str | None = None) -> dict:
    """Body-free names for a renderer's live cell or immutable History address."""
    from cell_write_scope import cell_write_scope
    from cell_placement import find_cell
    from state import require_channel
    from channel_db import open_channel_db
    from versions import find_tip

    ch = require_channel(channel)
    with cell_write_scope(channel, [cell_id], hold_state=True):
        cell = find_cell(ch, cell_id)[1]
        conn = open_channel_db(channel)
        try:
            address = version_id or (find_tip(conn, cell_id) if cell else cell_id)
            exists = conn.execute("SELECT 1 FROM cells WHERE id=?", (address,)).fetchone()
            if not exists and (version_id or cell is None):
                raise HTTPException(404, "Cell snapshot not found")
            if version_id is None:
                from builtin_packages import card_spec, projection
                from persistence import snapshot_files
                rows = snapshot_files(conn, cell_id)
                card = card_spec(ch, cell)
                paths = {f["path"] for f in (projection(card, rows) if card is not None else rows)}
            else:
                paths = set(tip_file_map(conn, address))
            return {"paths": sorted(paths)}
        finally:
            conn.close()


