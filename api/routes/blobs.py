@router.get("/api/channels/{channel}/cells/{cell_id}/files/{filepath:path}")
async def get_cell_file(channel: str, cell_id: str, filepath: str, request: Request, revision: int | None = None):
    """Serve immutable accepted/candidate bytes pinned to a file revision."""
    from persistence import read_file
    _refuse_service_worker_script(request)
    metadata, raw = await asyncio.to_thread(read_file, channel, cell_id, filepath, revision=revision)
    media_type = mimetypes.guess_type(filepath)[0] or ("text/plain" if metadata["encoding"] == "utf-8" else "application/octet-stream")
    headers = _cell_file_headers(media_type)
    headers.update({"X-File-Revision": str(metadata["file_revision"]), "X-Body-Hash": metadata["body_hash"],
                    "X-Writer-Id": metadata["writer_id"], "X-Edit-Seq": str(metadata["edit_seq"]),
                    "X-File-Encoding": metadata["encoding"], "ETag": f'"{metadata["body_hash"]}"'})
    return _accepted_body_response(raw, request, media_type, headers)


@router.get("/api/channels/{channel}/versions/{version_id}/files/{filepath:path}")
async def get_version_file(channel: str, version_id: str, filepath: str, request: Request):
    """Read exactly one committed snapshot, including a canvas cell's root.

    The same cell-file headers and capability boundary apply.
    """
    _refuse_service_worker_script(request)

    def resolve_blob():
        from channel_db import open_channel_db
        conn = open_channel_db(channel)
        try:
            return version_file_hashes(conn, version_id, [filepath]).get(filepath)
        finally:
            conn.close()

    return await _serve_file_blob(await asyncio.to_thread(resolve_blob), filepath)


async def _serve_file_blob(blob_hash: str | None, filepath: str):
    # Validate the immutable snapshot reference before constructing a CAS path.
    if not is_cas_hash(blob_hash):
        raise HTTPException(404, f"File '{filepath}' not found")
    assert isinstance(blob_hash, str)  # The CAS hash validator excludes null references.
    cas_path = blob_path(blob_hash)
    if not await asyncio.to_thread(os.path.isfile, cas_path):
        raise HTTPException(404, "Blob not found in CAS")
    media_type = mimetypes.guess_type(filepath)[0] or "application/octet-stream"
    # FileResponse supports ranges for media seeking. Both file addresses use
    # the same active-document sandbox and no-store policy.
    return _cas_response(blob_hash, media_type=media_type, headers=_cell_file_headers(media_type))


@dataclass(frozen=True)
class _RendererCandidate:
    channel: str
    cell_id: str
    roster: tuple[str, ...]
    descriptors: tuple
    manifest: dict
    prefix: str
    renderer_id: str
    references: dict[str, tuple[str, str]]


def _user_roster(channel) -> tuple[str, ...]:
    """The channel's Capabilities cells; the built-in cards serve from the build."""
    from cell_placement import capabilities_stack_cells
    return tuple(str(cell.id) for cell in capabilities_stack_cells(channel))


def _renderer_layout(channel=None):
    """Freeze only placement under state_lock (the active channel's unless
    ``channel`` is given); no SQL or body read."""
    from state import find_active_channel, state_lock
    with state_lock:
        channel = channel if channel is not None else find_active_channel()
        if channel is None:
            return None, None, ()
        return channel, str(channel.id), _user_roster(channel)


def _renderer_descriptors(channel: str, roster: tuple[str, ...]) -> tuple:
    """Read one coherent accepted SQL inventory without materializing bodies."""
    if not roster:
        return ()  # A new channel may not have a database yet.
    from database import get_db_connection
    from persistence import snapshot_files
    conn = get_db_connection(channel, create=False)
    try:
        conn.execute('BEGIN')
        return tuple((cell_id, tuple(snapshot_files(conn, cell_id))) for cell_id in roster)
    finally:
        conn.close()


def _scan_renderers(layout, *, include_disabled: bool = False, problems: list | None = None):
    """The user renderer packages of ``layout``'s Capabilities cells, read
    from accepted refs, independent of cell.files. A package that cannot
    serve is skipped and, with ``problems``, reported as ``{cell_id, path,
    error}``: an unreadable manifest, one without an id, a second package
    with the same id, or one that claims a built-in (``held_reason``: a
    built-in renderer's id or a surface extension), since moves and direct
    writes reach Capabilities without admission."""
    from builtin_packages import held_reason
    from cas import pin_blobs, require_blob
    from channel_config import read_renderer_availability, renderer_enabled
    from collimate.definitions import discover_definitions

    channel, channel_id, roster = layout
    if channel_id is None or not roster:
        return channel, []
    descriptors = _renderer_descriptors(channel_id, roster)
    avail = read_renderer_availability(channel_id)

    def report(cell_id, path, error):
        logger.warning('%s: %s; skipped', path, error)
        if problems is not None:
            problems.append({'cell_id': cell_id, 'path': path, 'error': error})

    candidates = []
    seen = set()
    for cell_id, files in descriptors:
        by_path = {file['path']: file for file in files}
        discovery = discover_definitions(by_path)
        for problem in discovery.problems:
            logger.warning('%s: %s', problem.path, problem.message)
        for package in discovery.packages:
            if package.kind != 'renderer':
                continue
            definition = by_path[package.definition_path]
            try:
                with pin_blobs([definition['body_hash']]):
                    manifest = yaml.safe_load(require_blob(definition['body_hash']).decode('utf-8')) or {}
            except (OSError, ValueError, UnicodeError, yaml.YAMLError) as exc:
                report(cell_id, package.definition_path, f'Renderer definition is unreadable: {exc}')
                continue
            if not isinstance(manifest, dict):
                report(cell_id, package.definition_path, 'Renderer definition must be a mapping')
                continue
            renderer_id = manifest.get('id')
            if not isinstance(renderer_id, str) or not renderer_id:
                report(cell_id, package.definition_path, 'Renderer id must be a nonempty string')
                continue
            held = held_reason('renderer', manifest)
            if held is not None:
                report(cell_id, package.definition_path, held)
                continue
            if renderer_id in seen:
                report(cell_id, package.definition_path, f'Duplicate renderer id {renderer_id!r}')
                continue
            seen.add(renderer_id)
            if not include_disabled and not renderer_enabled(avail, renderer_id):
                continue
            prefix = package.prefix + '/'
            references = {file['path']: ('blob', file['body_hash']) for file in files
                          if file['path'].startswith(prefix)
                          and '_runs' not in file['path'][len(prefix):].split('/')}
            candidates.append(_RendererCandidate(channel_id, cell_id, roster, descriptors,
                                                 manifest, prefix, renderer_id, references))
    return channel, candidates


def _renderer_inventory(*, include_disabled: bool = False):
    """The active channel's servable user renderers (see :func:`_scan_renderers`)."""
    return _scan_renderers(_renderer_layout(), include_disabled=include_disabled)


def renderer_inventory_problems(channel) -> list[dict]:
    """The user renderer packages in ``channel``'s Capabilities cells that
    are skipped, as ``{cell_id, path, error}`` rows."""
    problems: list[dict] = []
    _scan_renderers(_renderer_layout(channel), include_disabled=True, problems=problems)
    return problems


def _renderer_snapshot(renderer_id: str):
    """Select a renderer by its manifest ID: a built-in first (always
    available, from the build), else an enabled accepted user definition."""
    from builtin_packages import builtin_renderers
    if ".." in renderer_id or "/" in renderer_id or "\\" in renderer_id:
        raise HTTPException(400, "Invalid renderer ID")
    builtin = builtin_renderers().get(renderer_id)
    if builtin is not None:
        return builtin
    _channel, candidates = _renderer_inventory()
    selected = next((candidate for candidate in candidates if candidate.renderer_id == renderer_id), None)
    if selected is None:
        raise HTTPException(404, "Renderer not found in Capabilities")
    return selected


def _renderer_package(snapshot):
    from builtin_packages import BuiltinRenderer
    from renderer_bundles import package_bytes, bytes_source_hash
    if isinstance(snapshot, BuiltinRenderer):
        return dict(snapshot.files), snapshot.entrypoint, snapshot.source_hash, {}
    entrypoint = snapshot.manifest.get("entrypoint", "main.js")
    try:
        bodies, references = package_bytes(prefix=snapshot.prefix, entrypoint=entrypoint,
                                           channel=snapshot.channel, cell_id=snapshot.cell_id)
        if references != snapshot.references:
            raise ValueError('Renderer source changed during package capture')
        return bodies, entrypoint, bytes_source_hash(bodies, entrypoint=entrypoint), references
    except (ValueError, OSError) as exc:
        raise HTTPException(404, "Renderer package cannot be bundled") from exc


def _renderer_identity(snapshot):
    return _renderer_package(snapshot)[2]


@router.get("/api/renderers/{renderer_id}/package")
def get_renderer_package(renderer_id: str, v: str):
    """Return exact package bytes for an expected current source identity."""
    bodies, entrypoint, current, _references = _renderer_package(_renderer_snapshot(renderer_id))
    if v != current:
        raise HTTPException(404, "Renderer source version is no longer current")
    return JSONResponse({"source_hash": current, "entrypoint": entrypoint,
                         "files": {path: base64.b64encode(body).decode('ascii') for path, body in bodies.items()}},
                        headers={"Cache-Control": "no-store"})


class RendererBundleUpload(BaseModel):
    model_config = ConfigDict(extra="forbid")
    source_hash: str = Field(pattern=r"^[0-9a-f]{64}$")
    code: str


def _bundle_validator(snapshot: _RendererCandidate, renderer_id: str, references: dict):
    """The recheck a user renderer's uploaded bundle needs: the same active
    channel, roster, availability and accepted source refs."""
    from renderer_bundles import BundleConflict, current_body_references
    from state import find_active_channel, state_lock
    from channel_config import read_renderer_availability, renderer_enabled, ui_state_merge_lock
    from cas import publication_lock

    def validate_current():
        # SQL source commits take publication_lock. Hold it from the final
        # descriptor check with the existing state/UI lock order. Never retain
        # or commit bundle bytes while holding state_lock.
        with state_lock, ui_state_merge_lock(), publication_lock:
            try:
                channel = find_active_channel()
                roster = _user_roster(channel) if channel else ()
                if channel is None or str(channel.id) != snapshot.channel or roster != snapshot.roster:
                    raise BundleConflict('Renderer placement changed during upload')
                availability = read_renderer_availability(snapshot.channel)
                if not renderer_enabled(availability, renderer_id):
                    raise BundleConflict('Renderer was disabled during upload')
                current = _renderer_descriptors(snapshot.channel, snapshot.roster)
                current_refs = current_body_references(snapshot.channel, snapshot.cell_id, references)
            except (HTTPException, OSError, ValueError) as exc:
                raise BundleConflict("Renderer source changed during upload") from exc
            if current != snapshot.descriptors or current_refs != references:
                raise BundleConflict("Renderer source changed during upload")
    return validate_current


@router.put("/api/renderers/{renderer_id}/bundle")
def put_renderer_bundle(renderer_id: str, upload: RendererBundleUpload):
    """Cache the trusted user's compilation of the current enabled package
    (a built-in's: of the build's package)."""
    from builtin_packages import BuiltinRenderer
    from renderer_bundles import BundleConflict, publish_client_bundle

    snapshot = _renderer_snapshot(renderer_id)
    _bodies, _entrypoint, current, references = _renderer_package(snapshot)
    if current != upload.source_hash:
        raise HTTPException(409, "Renderer source version is no longer current")

    try:
        code = upload.code.encode('utf-8')
    except UnicodeError as exc:
        raise HTTPException(422, 'Renderer bundle must be valid UTF-8 text') from exc
    try:
        # A built-in's package is the build's, fixed for the server's lifetime.
        digest = publish_client_bundle(current, code, validate_current=(lambda: None)
                                       if isinstance(snapshot, BuiltinRenderer)
                                       else _bundle_validator(snapshot, renderer_id, references))
    except BundleConflict as exc:
        raise HTTPException(409, str(exc)) from exc
    return {"source_hash": current, "bundle_hash": digest}


@router.get("/api/renderers/{renderer_id}/source")
def get_renderer_source(renderer_id: str, request: Request, v: str | None = None):
    """Serve the current package's cached bundle, or 404 when unbuilt."""
    from renderer_bundles import get_bundle
    try:
        current_hash = _renderer_identity(_renderer_snapshot(renderer_id))
    except ValueError as exc:
        raise HTTPException(404, "Renderer package cannot be bundled") from exc
    if v is not None and v != current_hash:
        raise HTTPException(404, "Renderer source version is no longer current")
    code = get_bundle(current_hash)
    if code is None:
        raise HTTPException(404, "Renderer bundle is not built")
    etag = f'"{current_hash}"'
    headers = {
        "Cache-Control": "private, max-age=31536000, immutable" if v else "no-cache",
        "ETag": etag,
        "X-Entrypoint": "module.js",
    }
    candidates = request.headers.get("if-none-match", "").split(",")
    if any(candidate.strip().removeprefix("W/") in (etag, "*") for candidate in candidates):
        return Response(status_code=304, headers=headers)
    return Response(content=code, media_type="application/javascript", headers=headers)


def _row(manifest: dict, content_hash: str, *, cell_id, available: bool, builtin: bool) -> dict:
    rid = manifest["id"]
    return {
        "id": rid,
        "name": manifest.get("name") or rid,
        "version": manifest.get("version", "0.0.0"),
        "summary": manifest.get("summary", ""),
        "extensions": manifest.get("extensions", []),
        # The files this renderer is a default for: extensions it claims, or
        # "*" (offered under "Open with" for every text file).
        "default_for": manifest.get("default_for", []),
        "supports_diff": manifest.get("supports_diff", False),
        # The renderer refreshes itself in place on FILES_CHANGED —
        # hosts must not force-remount it to show an external write.
        "live_refresh": manifest.get("live_refresh", False),
        "embed": manifest.get("embed", "iframe"),
        "content_hash": content_hash,
        "cell_id": cell_id,
        "available": available,
        "builtin": builtin,
    }


def _without_surfaces(renderer: dict, key: str) -> None:
    """Strip the surface extensions (and any extension ending in one) from a
    user renderer's ``key`` list: those belong to the built-in renderers."""
    from builtin_packages import surface_of
    claims = renderer[key] if isinstance(renderer[key], list) else []
    kept = [claim for claim in claims if surface_of(claim) is None]
    if len(kept) != len(claims):
        logger.warning("renderer %r: %s %s belong to the app's built-in renderers; dropped", renderer["id"],
                       key, ", ".join(str(c) for c in claims if c not in kept))
    renderer[key] = kept


@router.get("/api/renderers")
def list_renderers(include_disabled: bool = False):
    """List renderers, deduplicated by id: the user's across the
    Capabilities cells, then the app's built-ins (``builtin: true``, always
    available, ``cell_id`` their card), last so a user renderer wins a
    same-length extension tie and ``text`` is the floor. A user renderer that
    claims a built-in id or a surface extension is never listed (it is a
    Capabilities problem), and its ``fallback_extensions`` never name a
    surface (stripped, logged). With no active channel: the built-ins only.

    By default off renderers are omitted (so resolution never binds a disabled
    renderer). ``include_disabled=1`` returns all of them stamped with
    ``available`` — used by the manage view, which must show off renderers to
    re-enable them. Every entry carries ``cell_id``, the cell that holds it.
    """
    from builtin_packages import builtin_renderers, renderer_card
    from channel_config import read_renderer_availability, renderer_enabled
    from handlers import catalog
    renderers = []
    ch, packages = _renderer_inventory(include_disabled=include_disabled)
    availability = read_renderer_availability(str(ch.id)) if packages and ch else {}
    for snapshot in packages:
        rid = snapshot.renderer_id
        try:
            content_hash = _renderer_identity(snapshot)
        except (ValueError, HTTPException):
            continue
        renderers.append(_row(snapshot.manifest, content_hash, cell_id=snapshot.cell_id,
                              available=renderer_enabled(availability, rid), builtin=False))
    users = list(renderers)
    renderers.extend(_row(renderer.manifest, renderer.source_hash, available=True, builtin=True,
                          cell_id=renderer_card(ch, renderer) if ch else None)
                     for renderer in builtin_renderers().values())
    aliases = catalog(ch).render_aliases() if ch else {}
    for renderer in renderers:
        # Keep declarations distinct: feeding expanded aliases into matching
        # would turn a one-step render_as rule into a transitive chain.
        claims = renderer['extensions']
        claims = claims if isinstance(claims, list) else []
        renderer['fallback_extensions'] = [
            ext for ext, target in aliases.items()
            if any(isinstance(claim, str) and target.endswith(claim.casefold()) for claim in claims)
        ]
    for renderer in users:
        _without_surfaces(renderer, 'fallback_extensions')
    return renderers
