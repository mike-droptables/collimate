"""Generate the client's copies of the api's constants from the api source.

The api owns these facts; the frontend mirrors them in one generated region
per file, between a ``// GENERATED by frontend/scripts/sync_app_constants.py``
line and ``// END GENERATED``, the rest of each file written by hand:

* ``frontend/src/lib/tags.ts``: ``TAG_MAX_LENGTH`` and ``TAGS_PER_CELL_MAX``
  from ``api/cell_tags.py``;
* ``frontend/src/lib/runningCell.ts``: ``RUNS_PREFIX`` from
  ``api/run_folders.py``.

The values are read from each module's literal assignment (``ast``), so the
script needs no api imports. ``api/tests/test_pytest_client_constants.py``
runs ``--check``.

    python3 frontend/scripts/sync_app_constants.py          # write the regions
    python3 frontend/scripts/sync_app_constants.py --check  # list what differs; exit 1 if any
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = "frontend/scripts/sync_app_constants.py"
# Each target and, in order, the api module and constants its region holds.
TARGETS = {
    "frontend/src/lib/tags.ts": ("api/cell_tags.py", ("TAG_MAX_LENGTH", "TAGS_PER_CELL_MAX")),
    "frontend/src/lib/runningCell.ts": ("api/run_folders.py", ("RUNS_PREFIX",)),
}


def constants(source: str, names) -> dict:
    """``names`` as ``source`` assigns them at module level, each a literal."""
    tree = ast.parse((ROOT / source).read_text(encoding="utf-8"), source)
    found = {}
    for node in tree.body:
        target = node.targets[0] if isinstance(node, ast.Assign) and len(node.targets) == 1 else (
            node.target if isinstance(node, ast.AnnAssign) else None)
        if isinstance(target, ast.Name) and target.id in names and node.value is not None:
            found[target.id] = ast.literal_eval(node.value)
    missing = [name for name in names if name not in found]
    if missing:
        raise SystemExit(f"{source}: no module-level literal {', '.join(missing)}")
    return {name: found[name] for name in names}


def _literal(value) -> str:
    if isinstance(value, bool) or not isinstance(value, (int, str)):
        raise SystemExit(f"cannot write {value!r} as a TypeScript constant")
    if isinstance(value, int):
        return str(value)
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _replace_region(text: str, path: str, source: str, lines: list) -> str:
    pattern = re.compile(rf"(?m)^// GENERATED by {re.escape(SCRIPT)}\b[^\n]*\n.*?^// END GENERATED\n", re.DOTALL)
    found = len(pattern.findall(text))
    if found != 1:
        raise SystemExit(f"{path}: expected one generated region, found {found}")
    region = (f"// GENERATED by {SCRIPT} from {source}; do not edit.\n"
              + "".join(f"{line}\n" for line in lines) + "// END GENERATED\n")
    return pattern.sub(lambda _match: region, text)


def expected() -> dict:
    """Every target path and the text it must hold."""
    out = {}
    for path, (source, names) in TARGETS.items():
        lines = [f"export const {name} = {_literal(value)};" for name, value in constants(source, names).items()]
        out[ROOT / path] = _replace_region((ROOT / path).read_text(encoding="utf-8"), path, source, lines)
    return out


def main(argv: list) -> int:
    targets = expected()
    stale = [path for path, text in targets.items() if path.read_text(encoding="utf-8") != text]
    if "--check" in argv:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run python3 {SCRIPT})")
        return 1 if stale else 0
    for path in stale:
        path.write_text(targets[path], encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
