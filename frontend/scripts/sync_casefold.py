"""Generate client case-fold exceptions from the API Python Unicode table.

``frontend/src/lib/unicodeCaseFold.ts`` holds every code point whose
``str.casefold`` differs from its ``str.lower``. The table follows the
interpreter's Unicode version, so run this under the workspace's Python, the
one the api runs on (``uv run``), not whatever ``python3`` is on PATH.
``api/tests/test_pytest_renderer_aliases.py`` pins the bytes.

    uv run python frontend/scripts/sync_casefold.py          # write the table
    uv run python frontend/scripts/sync_casefold.py --check  # exit 1 if it differs
"""
import json
import re
import sys
import unicodedata
from pathlib import Path

SCRIPT = "frontend/scripts/sync_casefold.py"
TARGET = Path(__file__).resolve().parents[1] / 'src/lib/unicodeCaseFold.ts'


def generated():
    pairs = {chr(i): chr(i).casefold() for i in range(0x110000)
             if chr(i).casefold() != chr(i).lower()}
    return (
        f"// Unicode {unicodedata.unidata_version} case-fold exceptions to per-code-point lowercasing.\n"
        "// Generated by frontend/scripts/sync_casefold.py; do not edit the table by hand.\n"
        "const exceptions: Record<string,string> = "
        + json.dumps(pairs, ensure_ascii=True, separators=(',', ':')) + ";\n"
        "export function caseFold(value:string):string {\n"
        "  return Array.from(value, char => exceptions[char] ?? char.toLowerCase()).join('');\n}\n"
    )


HEADER = re.compile(r"^// Unicode (\S+) case-fold exceptions")


def committed_unicode_version() -> "str | None":
    """The Unicode version the committed table was generated from (its
    header line), or None when there is no table yet."""
    if not TARGET.is_file():
        return None
    m = HEADER.match(TARGET.read_text(encoding="utf-8"))
    return m.group(1) if m else None


def main(argv: list) -> int:
    if argv not in ([], ["--check"], ["--allow-unicode-change"]):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    # The table follows the interpreter's Unicode version: a bare python3 on a
    # newer system Python would rewrite it to another table, silently. Only a
    # deliberate run moves it.
    committed = committed_unicode_version()
    if committed is not None and committed != unicodedata.unidata_version and argv != ["--allow-unicode-change"]:
        print(f"refused: frontend/src/lib/unicodeCaseFold.ts is Unicode {committed}; this Python's table is "
              f"Unicode {unicodedata.unidata_version}. Run it under the workspace Python (uv run python {SCRIPT}), "
              "or pass --allow-unicode-change to move the table to this one.", file=sys.stderr)
        return 1
    text = generated()
    stale = not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != text
    if argv == ["--check"]:
        if stale:
            print(f"stale: frontend/src/lib/unicodeCaseFold.ts (Unicode {unicodedata.unidata_version} here; "
                  f"run uv run python {SCRIPT})")
        return 1 if stale else 0
    if stale:
        TARGET.write_text(text, encoding="utf-8")
        print("wrote frontend/src/lib/unicodeCaseFold.ts")
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
