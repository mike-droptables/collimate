// mirrorUrl: the app's same-origin copy of a module-CDN URL.
//
// The app serves the module CDNs in MIRRORED_HOSTS from its own origin at
// <api>/mirror/<host>/…, beside this runtime (<api>/sdk/react.js), and its
// document import maps send ES module imports there. A load that an
// import map does not cover (a fetched stylesheet, a font, wasm, an AMD
// <script>, a worker) goes through mirrorUrl. Any other URL is returned
// unchanged, as is every URL wherever this runtime is not served by the app
// (a sealed preview, a test): there is no mirror beside it to route to.

// GENERATED by sdk/scripts/sync_mirror_hosts.py from sdk/src/collimate/module_mirror_contract.json `upstreams`; do not edit.
const MIRRORED_HOSTS: ReadonlySet<string> = new Set(['esm.sh', 'cdn.jsdelivr.net']);
// END GENERATED

const RUNTIME_URL: string = import.meta.url;

export function mirrorUrl(url: string): string {
    if (!/^https?:\/\//.test(RUNTIME_URL)) return url;
    let parsed: URL;
    try {
        parsed = new URL(url);
    } catch {
        return url;
    }
    if (parsed.protocol !== 'https:' || !MIRRORED_HOSTS.has(parsed.host) || parsed.username || parsed.password) {
        return url;
    }
    return new URL(`../mirror/${parsed.host}/${parsed.pathname.slice(1)}${parsed.search}`, RUNTIME_URL).href;
}
