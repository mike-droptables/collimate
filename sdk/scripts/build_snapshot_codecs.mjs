#!/usr/bin/env node
// Build approved, self-contained codecs; their source is durably cached by the
// document owner before it accepts any snapshot referring to the source hash.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// The approved hashes stay with the runtime (a git-ignored output that
// shared/renderer-runtime/index.json pins); the milkdown renderer, in the
// workspace's content tree, carries the built codec it registers (committed).
export const outputs = {
    descriptor: path.resolve(root, '../content/renderers/documents/milkdown/snapshot-codec.ts'),
    manifest: path.join(root, 'shared/renderer-runtime/snapshot-codecs.json'),
};
/** The descriptor's and the manifest's text, keyed as in `outputs`. */
export async function snapshotCodecs() {
    const result = await build({
        absWorkingDir: root,
        entryPoints: ['scripts/snapshot-codecs/milkdown.ts'],
        bundle: true, write: false, format: 'iife', platform: 'browser',
        // Select the DOM-free character-reference decoder while retaining
        // browser crypto. The CDN browser graph otherwise accesses document.
        conditions: ['worker'], target: 'es2022', minify: true,
        legalComments: 'inline',
    });
    const source = result.outputFiles[0].text;
    const codec = {
        id: 'collimate.milkdown-pm', version: 1,
        implementationHash: createHash('sha256').update(source).digest('hex'), source,
    };
    const descriptor = '// Generated by sdk/scripts/build_snapshot_codecs.mjs. Do not edit.\n'
        + 'export const milkdownSnapshotCodec = ' + JSON.stringify(codec) + ';\n';
    const { source: _source, ...approved } = codec;
    const manifest = JSON.stringify({ codecs: [approved] }, null, 2) + '\n';
    return { descriptor, manifest };
}
// Alone (--check compares; a manifest not built yet is skipped). The runtime
// build, which hashes both, runs this as its first step.
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
    const check = process.argv.includes('--check');
    const built = await snapshotCodecs();
    for (const [key, bytes] of Object.entries(built)) {
        const destination = outputs[key];
        if (check) {
            const existing = await readFile(destination, 'utf8').catch(error => {
                if (error.code === 'ENOENT' && key === 'manifest') return bytes;
                throw error;
            });
            if (existing !== bytes) throw Error('Snapshot codec differs: ' + destination);
        } else {
            await mkdir(path.dirname(destination), { recursive: true });
            await writeFile(destination, bytes);
        }
    }
}
