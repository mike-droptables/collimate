#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Project the channel SSE records and the IPC op table into the files other
languages read.

The records are the dataclasses in ``src/collimate/_host/channel_events.py``; the
app emits them. The op table is ``OPS`` in ``src/collimate/_host/ipc.py``. This
script writes

* ``shared/contracts/channel-events.schema.json``: a JSON Schema giving each
  record's field names and JSON types;
* ``frontend/src/generated/channelEvents.ts`` (in the workspace): one
  interface per record and the ``ChannelEvent`` union the app's dispatcher
  switches on;
* ``shared/contracts/ipc-ops.json``: every op in table order with its kind
  and capability, which the codebase map's build counts.

Field names and primitive types come from the annotations. A field whose
annotation is too loose for TypeScript (a ``dict``, a ``str`` with a fixed
set of values) takes its type from ``TS_TYPES``. ``tests/test_contracts.py``
pins the bytes, and the app's ``api/tests/test_pytest_contracts.py`` pins its
copy.

    python3 sdk/scripts/sync_contracts.py          # write the projections
    python3 sdk/scripts/sync_contracts.py --check  # list what differs; exit 1 if any
"""
from __future__ import annotations

import ast
import json
import sys
import types
import typing
from dataclasses import fields
from pathlib import Path

SDK = Path(__file__).resolve().parents[1]
WORKSPACE = SDK.parent
sys.path.insert(0, str(SDK / "src"))

from collimate._host import channel_events, ipc  # noqa: E402

COMMAND = "python3 sdk/scripts/sync_contracts.py"
SCHEMA = SDK / "shared" / "contracts" / "channel-events.schema.json"
TS = WORKSPACE / "frontend" / "src" / "generated" / "channelEvents.ts"
OPS_JSON = SDK / "shared" / "contracts" / "ipc-ops.json"

#: The TypeScript of fields whose annotation does not say enough:
#: (record, field) -> type. The named types come from TS_IMPORTS.
TS_TYPES = {
    ("StateSnapshot", "state"): "ScopedAppState",
    ("StateDelta", "patches"): "StatePatch[]",
    ("FileChanges", "outcome"): "FileMutationResult['outcome']",
    ("FileChanges", "files"): "FileMutationResult['files']",
    ("FileChanges", "conflicts"): "FileMutationResult['conflicts']",
    ("RunStatus", "outcome"): "RunOutcome | null",
}
#: The app modules that define the named types TS_TYPES uses.
TS_IMPORTS = {
    "@/lib/fileProtocol": ("FileMutationResult",),
    "@/lib/types": ("ScopedAppState", "StatePatch"),
}
#: Literal unions an SDK constant states: TypeScript name -> collimate._host.ipc name.
TS_LITERALS = {"RunOutcome": "FINISH_OUTCOMES"}

_JSON = {str: "string", int: "integer", float: "number", bool: "boolean", dict: "object"}
_TS = {str: "string", int: "number", float: "number", bool: "boolean", dict: "Record<string, unknown>"}


def _fields(cls) -> dict:
    """A record's fields (or a TypedDict's keys) and their types, in order."""
    hints = typing.get_type_hints(cls)
    return hints if typing.is_typeddict(cls) else {f.name: hints[f.name] for f in fields(cls)}


def _optional(tp) -> tuple:
    """``tp`` without its ``| None``, and whether it had one."""
    args = typing.get_args(tp)
    if typing.get_origin(tp) in (types.UnionType, typing.Union) and type(None) in args:
        [rest] = [arg for arg in args if arg is not type(None)]
        return rest, True
    return tp, False


def _json_type(tp, defs: dict) -> dict:
    tp, nullable = _optional(tp)
    if typing.get_origin(tp) is list:
        out = {"type": "array", "items": _json_type(typing.get_args(tp)[0], defs)}
    elif typing.is_typeddict(tp):
        if tp.__name__ not in defs:
            defs[tp.__name__] = _json_object(None, _fields(tp), defs)
        out = {"$ref": f"#/$defs/{tp.__name__}"}
    else:
        out = {"type": _JSON[typing.get_origin(tp) or tp]}
    if not nullable:
        return out
    if "$ref" in out:
        return {"anyOf": [out, {"type": "null"}]}
    return {**out, "type": [out["type"], "null"]}


def _json_object(tag, hints: dict, defs: dict) -> dict:
    properties = {"type": {"const": tag}} if tag else {}
    properties.update({name: _json_type(tp, defs) for name, tp in hints.items()})
    return {"type": "object", "properties": properties, "required": list(properties),
            "additionalProperties": False}


def schema_source() -> str:
    defs: dict = {}
    records = {cls.__name__: _json_object(tag, _fields(cls), defs)
               for tag, cls in channel_events.EVENT_TYPES.items()}
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": "GENERATED by sdk/scripts/sync_contracts.py from "
                    "sdk/src/collimate/_host/channel_events.py; do not edit.",
        "title": "ChannelEvent",
        "description": "A record on a channel's SSE stream; `type` names it.",
        "oneOf": [{"$ref": f"#/$defs/{name}"} for name in records],
        "$defs": {**records, **defs},
    }
    return json.dumps(schema, indent=2) + "\n"


def _ts_type(tp, named: dict) -> str:
    tp, nullable = _optional(tp)
    if typing.get_origin(tp) is list:
        inner = _ts_type(typing.get_args(tp)[0], named)
        text = f"({inner})[]" if " " in inner else f"{inner}[]"
    elif typing.is_typeddict(tp):
        named[tp.__name__] = tp
        text = tp.__name__
    else:
        text = _TS[typing.get_origin(tp) or tp]
    return f"{text} | null" if nullable else text


def _docstrings() -> dict:
    tree = ast.parse(Path(channel_events.__file__).read_text(encoding="utf-8"))
    return {node.name: ast.get_docstring(node) for node in tree.body if isinstance(node, ast.ClassDef)}


def _jsdoc(text) -> str:
    if not text:
        return ""
    if "*/" in text:
        raise SystemExit("a channel_events docstring holds '*/', which would end its TS comment")
    lines = text.replace("``", "`").splitlines()
    if len(lines) == 1:
        return f"/** {lines[0]} */\n"
    return "/**\n" + "".join(f" * {line}".rstrip() + "\n" for line in lines) + " */\n"


def _interface(name: str, members: list, doc) -> str:
    return _jsdoc(doc) + f"export interface {name} {{\n" + "".join(f"  {m};\n" for m in members) + "}\n"


def typescript_source() -> str:
    docs, named, used, records = _docstrings(), {}, set(), []
    for tag, cls in channel_events.EVENT_TYPES.items():
        members = [f"type: '{tag}'"]
        for field, tp in _fields(cls).items():
            key = (cls.__name__, field)
            used.add(key)
            members.append(f"{field}: {TS_TYPES[key] if key in TS_TYPES else _ts_type(tp, named)}")
        records.append(_interface(cls.__name__, members, docs.get(cls.__name__)))
    if unused := sorted(set(TS_TYPES) - used):
        raise SystemExit(f"TS_TYPES names fields no record has: {unused}")
    parts = [
        "// GENERATED by sdk/scripts/sync_contracts.py from sdk/src/collimate/_host/channel_events.py,\n"
        "// the records the app emits on a channel's SSE stream. Do not edit: change the\n"
        "// dataclasses (or the script's TS_TYPES) and rerun it.\n",
        "".join(f"import type {{ {', '.join(names)} }} from '{module}';\n"
                for module, names in TS_IMPORTS.items()),
    ]
    for name, constant in TS_LITERALS.items():
        values = " | ".join(f"'{value}'" for value in sorted(getattr(ipc, constant)))
        parts.append(f"/** The values of `collimate._host.ipc.{constant}`. */\nexport type {name} = {values};\n")
    parts += [_interface(name, [f"{key}: {_ts_type(tp, named)}" for key, tp in _fields(td).items()],
                         docs.get(name)) for name, td in named.items()]
    parts += records
    union = "".join(f"\n  | {cls.__name__}" for cls in channel_events.EVENT_TYPES.values())
    parts.append(f"/** A record on a channel's SSE stream; `type` names it. */\n"
                 f"export type ChannelEvent ={union};\n")
    return "\n".join(parts)


def ops_source() -> str:
    table = {
        "$comment": "GENERATED by sdk/scripts/sync_contracts.py from "
                    "sdk/src/collimate/_host/ipc.py (OPS); do not edit.",
        "ops": [{"name": name, "kind": spec.kind, "capability": spec.capability}
                for name, spec in ipc.OPS.items()],
    }
    return json.dumps(table, indent=2) + "\n"


def expected() -> dict:
    return {SCHEMA: schema_source(), TS: typescript_source(), OPS_JSON: ops_source()}


def main(argv: list) -> int:
    targets = expected()
    stale = [path for path, text in targets.items()
             if not path.is_file() or path.read_text(encoding="utf-8") != text]
    if "--check" in argv:
        for path in stale:
            print(f"stale: {path.relative_to(WORKSPACE)} (run {COMMAND})")
        return 1 if stale else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(targets[path], encoding="utf-8")
        print(f"wrote {path.relative_to(WORKSPACE)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
