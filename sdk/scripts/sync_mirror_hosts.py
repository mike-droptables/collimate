"""Project the module mirror's hosts into the files that route them.

``src/collimate/module_mirror_contract.json`` ``upstreams`` is the one list of
module CDNs the app mirrors. Python reads it at import
(:data:`collimate._host.module_mirror.HOSTS`, and the app's served import map is
built from that); TypeScript and static HTML cannot, so this script writes the
hosts into one generated region of each file that names them:

* ``sdk/packages/renderer-hooks/src/mirror.ts``: the runtime's ``MIRRORED_HOSTS``;
* ``frontend/src/lib/moduleMirror.ts``: the app's ``MIRRORED_HOSTS``;
* ``frontend/index.html``: the default ``collimate-mirror-map`` import map;
* ``frontend/public/sandbox.html``: the iframe's ``hosts``;
* ``frontend/src/test/browser-tester.html``: the browser tests' import map.

The frontend files lie outside the SDK. They copy an SDK contract, so their
generator lives beside it until a repo-level ``scripts/generate.py`` runs
every generator. Each TypeScript and JavaScript region sits between a
``// GENERATED by sdk/scripts/sync_mirror_hosts.py …`` line and
``// END GENERATED``; each HTML region is the body of the
``collimate-mirror-map`` import map, which a ``<!-- GENERATED … -->`` comment
follows (the map must open ``<head>``). Everything else in the files is
written by hand.

``mirror.ts`` is a hashed input of ``shared/renderer-runtime/index.json``:
after this rewrites it, rebuild the runtime
(``node scripts/build_renderer_runtime.mjs``).
``tests/test_module_mirror.py`` runs ``--check``.

    python3 sdk/scripts/sync_mirror_hosts.py          # write the regions
    python3 sdk/scripts/sync_mirror_hosts.py --check  # list what differs; exit 1 if any
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT.parent
CONTRACT = ROOT / "src" / "collimate" / "module_mirror_contract.json"
SCRIPT = "sdk/scripts/sync_mirror_hosts.py"
SOURCE = "sdk/src/collimate/module_mirror_contract.json"
_UPSTREAM = re.compile(r"^https://([a-z0-9-]+(?:\.[a-z0-9-]+)+)/$")


def hosts(contract: Path = CONTRACT) -> tuple:
    """The contract's ``upstreams`` as bare host names, in order."""
    out = []
    for upstream in json.loads(contract.read_text(encoding="utf-8"))["upstreams"]:
        match = _UPSTREAM.match(upstream)
        if not match:
            raise SystemExit(f"{SOURCE}: upstream {upstream!r} is not https://<host>/")
        out.append(match.group(1))
    return tuple(out)


def _ts_list(names) -> str:
    return "[" + ", ".join(f"'{name}'" for name in names) + "]"


def _import_map(names, base: str) -> str:
    """The import map sending each host to ``<base><host>/``, as the app's
    server builds it (``api/main.py`` ``_mirror_import_map``)."""
    imports = {f"https://{name}/": f"{base}{name}/" for name in names}
    return json.dumps({"imports": imports}, separators=(",", ":")).replace("<", "\\u003c")


def _replace_code(text: str, path: str, lines: list) -> str:
    """Replace the ``// GENERATED by`` … ``// END GENERATED`` region's body."""
    pattern = re.compile(rf"(?m)^(?P<i>[ \t]*)// GENERATED by {re.escape(SCRIPT)}\b[^\n]*\n.*?^(?P=i)// END GENERATED\n",
                         re.S)
    matches = pattern.findall(text)
    if len(matches) != 1:
        raise SystemExit(f"{path}: expected one generated region, found {len(matches)}")

    def body(match) -> str:
        pad = match.group("i")
        return (f"{pad}// GENERATED by {SCRIPT} from {SOURCE} `upstreams`; do not edit.\n"
                + "".join(f"{pad}{line}\n" for line in lines) + f"{pad}// END GENERATED\n")
    return pattern.sub(body, text)


def _replace_map(text: str, path: str, body: str) -> str:
    """Replace the body of the ``collimate-mirror-map`` import map, which a
    ``<!-- GENERATED by`` comment must follow."""
    pattern = re.compile(r'(<script type="importmap" id="collimate-mirror-map">)[^<]*'
                         rf"(</script>\n[ \t]*<!-- GENERATED by {re.escape(SCRIPT)}\b)")
    if len(pattern.findall(text)) != 1:
        raise SystemExit(f"{path}: expected one collimate-mirror-map import map followed by its GENERATED comment")
    return pattern.sub(lambda match: match.group(1) + body + match.group(2), text)


def expected(names=None) -> dict:
    """Every target path and the text it must hold."""
    names = names or hosts()
    hooks = ROOT / "packages" / "renderer-hooks" / "src" / "mirror.ts"
    frontend = WORKSPACE / "frontend"
    code = {
        hooks: [f"const MIRRORED_HOSTS: ReadonlySet<string> = new Set({_ts_list(names)});"],
        frontend / "src" / "lib" / "moduleMirror.ts":
            [f"export const MIRRORED_HOSTS: ReadonlySet<string> = new Set({_ts_list(names)});"],
        frontend / "public" / "sandbox.html": [f"const hosts = {_ts_list(names)};"],
    }
    maps = {
        frontend / "index.html": "../api/mirror/",
        frontend / "src" / "test" / "browser-tester.html": "/api/mirror/",
    }
    out = {}
    for path, lines in code.items():
        out[path] = _replace_code(path.read_text(encoding="utf-8"), str(path.relative_to(WORKSPACE)), lines)
    for path, base in maps.items():
        out[path] = _replace_map(path.read_text(encoding="utf-8"), str(path.relative_to(WORKSPACE)),
                                 _import_map(names, base))
    return out


def main(argv: list) -> int:
    targets = expected()
    stale = [path for path, text in targets.items() if path.read_text(encoding="utf-8") != text]
    if "--check" in argv:
        for path in stale:
            print(f"stale: {path.relative_to(WORKSPACE)} (run python3 {SCRIPT})")
        return 1 if stale else 0
    for path in stale:
        path.write_text(targets[path], encoding="utf-8")
        print(f"wrote {path.relative_to(WORKSPACE)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
