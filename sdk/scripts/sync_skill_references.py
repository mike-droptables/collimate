"""Regenerate accepted handler skill references and the Guide's two mirrors.

Canonical authoring guides live in the SDK's ``shared/docs``. They travel with
the accepted built-in handlers (the workspace's ``builtins/definitions``) in
``derived/skills/**/references/``; the Guide preset carries only
its overview and philosophy references. This script removes stray mirror
files and updates the built-in handlers' accepted derived hashes in the same
invocation.
``tests/test_skill_references.py`` pins both the bytes and accepted hashes.

    python scripts/sync_skill_references.py          # write the mirrors
    python scripts/sync_skill_references.py --check  # list what differs; exit 1 if any

The app pins every built-in package by content hash (``api/builtins.json``),
so a sync that writes under ``builtins/`` is followed by the app's updater,
``PYTHONPATH=api uv run python build/sync_builtins.py`` from the workspace
root; a committed tree passes both ``--check`` runs.
"""
from __future__ import annotations

import shutil
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT.parent
DOCS = ROOT / "shared" / "docs"
AGENT = WORKSPACE / "content" / "generators" / "agent"
HANDLERS = WORKSPACE / "builtins" / "definitions"
HANDLER_DOCS = {
    "renderer": ("how-to-write-a-renderer.md", "api-reference.md", "how-to-write-a-verifier.md", "interface.md"),
    "generator": ("how-to-write-a-generator.md", "api-reference.md", "testing-generators.md", "interface.md"),
    "runner": ("how-to-write-a-runner.md",),
    "handler": ("how-to-write-a-handler.md", "how-to-write-a-verifier.md", "interface.md"),
    "options": ("how-to-write-options.md",),
}

# preset → (skill folder, the docs its references hold; None = every doc)
PRESETS: dict = {
    "guide": ("collimate-guide", ("collimate-overview.md", "why-collimate.md")),
}


def _reference_dirs(preset: str, skill: str) -> list:
    """The preset's config in the Agent cell's generator, loaded into a
    saved runner by the user."""
    tail = Path("files") / "_skills" / skill / "references"
    return [AGENT / "agent" / "configs" / preset / tail]


def _folder(handler: str) -> Path:
    return HANDLERS / handler


def expected() -> dict:
    """``{mirror path: bytes}`` for every reference file a mirror must hold."""
    out: dict = {}
    for preset, (skill, names) in PRESETS.items():
        docs = sorted(p.name for p in DOCS.glob("*.md")) if names is None else list(names)
        for folder in _reference_dirs(preset, skill):
            for name in docs:
                out[folder / name] = (DOCS / name).read_bytes()
    for handler, names in HANDLER_DOCS.items():
        folder = _folder(handler) / "derived" / "skills" / f"{handler}-authoring" / "references"
        for name in names:
            out[folder / name] = (DOCS / name).read_bytes()
    out[HANDLERS / "handler/derived/skills/build/references/how-to-write-a-verifier.md"] = (DOCS / "how-to-write-a-verifier.md").read_bytes()
    out[HANDLERS / "handler/derived/skills/build/references/interface.md"] = (DOCS / "interface.md").read_bytes()
    return out


def _accepted_manifests(references: dict) -> dict:
    """Shipped acceptance tracks the same generated bytes, in this one sync."""
    sys.path.insert(0, str(ROOT / "src"))
    from collimate.handlers import derived_hash
    out = {}
    for folder in sorted(HANDLERS.glob("*")):
        manifests = list(folder.glob("*.handler"))
        if len(manifests) != 1 or not (folder / "derived").is_dir():
            continue
        derived = folder / "derived"
        files = {p.relative_to(derived).as_posix(): p.read_bytes()
                 for p in derived.rglob("*") if p.is_file() and not p.is_symlink()}
        # Mirrors being added/replaced/removed must enter the hash in the same
        # invocation, including a clean checkout with no generated references.
        reference_dirs = {p.parent for p in references
                          if p.is_relative_to(derived)}
        files = {name: body for name, body in files.items()
                 if not any((derived/name).is_relative_to(parent) for parent in reference_dirs)}
        files.update({p.relative_to(derived).as_posix(): body for p, body in references.items()
                      if p.is_relative_to(derived)})
        text = manifests[0].read_text()
        line = "derived: " + derived_hash(files)
        text = re.sub(r"^derived:.*$", line, text, flags=re.MULTILINE) if re.search(r"^derived:", text, re.MULTILINE) else text.rstrip() + "\n" + line + "\n"
        out[manifests[0]] = text.encode()
    return out


def differences() -> list:
    """Missing, changed or stray mirrors and outdated accepted manifests."""
    want = expected()
    stale = [p for p, data in want.items() if not p.is_file() or p.read_bytes() != data]
    folders = {p.parent for p in want}
    extra = [p for folder in folders if folder.is_dir()
             for p in folder.iterdir() if p not in want]
    stale.extend(p for p, data in _accepted_manifests(want).items() if p.read_bytes() != data)
    return sorted(stale + extra)


def sync() -> list:
    """Write every mirror and remove what should not be there; returns the
    paths changed."""
    changed = differences()
    want = expected()
    want.update(_accepted_manifests(want))
    for path in changed:
        if path in want:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(want[path])
        elif path.is_dir() and not path.is_symlink():
            shutil.rmtree(path)
        else:
            path.unlink()
    return changed


def main(argv: list) -> int:
    if "--check" in argv:
        changed = differences()
        for path in changed:
            print(path.relative_to(WORKSPACE))
        return 1 if changed else 0
    for path in sync():
        print(f"synced {path.relative_to(WORKSPACE)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
