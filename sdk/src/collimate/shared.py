"""This SDK's own files at runtime: its ``shared/`` tree and its metadata.

The ``shared/`` directory lives at the SDK member's root (beside
``src/``). It holds the authoring how-to docs (``shared/docs/*.md``) — the
canonical, GitHub-browsable source — and is the landing spot for any
cross-cutting, non-Python asset the SDK wants to expose.

Two resolution paths:

1. Installed wheel — ``importlib.resources.files("collimate") / "shared" / ...``.
   The build hook (``build/hatch_build.py``) puts ``sdk/shared`` into the
   wheel as ``collimate/shared``.

2. In-tree source / editable checkout — fall through to the SDK repo
   root (computed from this file's location) and join ``shared/`` + the
   requested segments.

The returned ``Path`` is always a real filesystem path (the installed
package directory or the checkout); zip / zipimport installs are not
supported — a resource that is not on disk is not found.

:func:`sdk_distribution` reads the metadata of the ``collimate``
distribution this SDK source belongs to (``_sdk_metadata/``, the bytes the
wheel's dist-info holds), and :func:`sdk_requirements` the SDK packages' own
runtime requirements within it: what the generator build and test tooling
that stage the SDK source install beside it.
"""
from __future__ import annotations

import functools
import hashlib
import json
from collections.abc import Iterable
from importlib.metadata import Distribution
from importlib.resources import files
from pathlib import Path


_IN_TREE_SDK_ROOT = Path(__file__).resolve().parents[2]


def shared_path(*segments: str) -> Path:
    """Resolve a path inside the SDK's ``shared/`` directory.

    Raises ``FileNotFoundError`` with both attempted locations in the
    message when neither lookup finds the asset.

    Example:
        >>> shared_path("docs", "how-to-write-a-generator.md").read_text()[:20]
        '# How to write a gen'
    """
    rel = "/".join(segments)

    # 1. Installed wheel — importlib.resources.
    try:
        installed = files("collimate").joinpath("shared", *segments)
        if isinstance(installed, Path) and installed.exists():
            return installed
    except (ModuleNotFoundError, FileNotFoundError):
        pass

    # 2. In-tree / editable checkout.
    in_tree = _IN_TREE_SDK_ROOT / "shared" / rel
    if in_tree.exists():
        return in_tree

    raise FileNotFoundError(
        f"Cannot locate shared asset {rel!r}. "
        f"Checked installed package resources (collimate/shared/{rel}) "
        f"and the in-tree path {in_tree}."
    )


def toolchain() -> dict:
    """The toolchain contract, ``shared/contracts/toolchain.json``: the Node
    range every workflow installs (``node``) and the renderer runtime's React
    (``react``, ``react_dom``) with its type packages (``types_react``,
    ``types_react_dom``). The renderer compiler's esbuild is not restated
    there: ``collimate._host.renderer_bundle.CONTRACT["esbuild_version"]``.
    ``scripts/sync_toolchain.py`` writes these values into the npm manifests
    and workflows that cannot read them."""
    return json.loads(shared_path("contracts", "toolchain.json").read_text(encoding="utf-8"))


#: The projections whose bytes are the API contract, in hash order: the
#: channel SSE records and the IPC op table (``sdk/scripts/sync_contracts.py``
#: writes both from ``collimate._host``).
CONTRACT_FILES = ("channel-events.schema.json", "ipc-ops.json")


def contract_digest(texts: Iterable[str]) -> str:
    """The contract version of the ``CONTRACT_FILES`` texts, in order: the
    first 16 hex digits of a sha256 over each one's UTF-8 bytes and a NUL.
    Two builds speak one contract exactly when their projections are byte
    for byte the same."""
    digest = hashlib.sha256()
    for text in texts:
        digest.update(text.encode("utf-8"))
        digest.update(b"\0")
    return digest.hexdigest()[:16]


@functools.cache
def api_contract() -> str:
    """The API contract this installation speaks, as ``/health`` reports it
    under ``contract``: :func:`contract_digest` of the shipped projections.
    The desktop shell pins its own copy (``desktop/src/shared/apiContract.ts``,
    generated by ``sync_contracts.py``) and marks a server whose contract
    differs as one it cannot speak."""
    return contract_digest(shared_path("contracts", name).read_text(encoding="utf-8")
                           for name in CONTRACT_FILES)


# What ``collimate`` and ``gen`` import beyond the standard library: the part
# of the distribution's requirements the SDK packages need where they travel
# alone (the container base image installs exactly these, a forwarded draft
# test runs with them). The server's requirements are the rest. A test keeps
# each one equal to its line in pyproject.toml, and the import-boundary walk
# imports every SDK module with nothing else installed.
SDK_REQUIREMENTS = ("pyyaml>=6.0",)
# The oldest Python the SDK packages run on: the generators' PEP 723 headers
# declare it (a test keeps them equal), and sdk/ruff.toml lints at it. The
# distribution's own floor is the server's, 3.13.
SDK_REQUIRES_PYTHON = ">=3.12"
# Where the collimate wheel puts the SDK packages, collimate and gen: a
# directory of their own beside the server's packages in site-packages, put on
# sys.path by the wheel's <WHEEL_SDK_HOME>.pth (build/hatch_build.py). Nothing
# else is in it, so a generator run takes it as its PYTHONPATH and sees the SDK
# and none of the server's dependencies; a checkout's sdk/src is the same.
WHEEL_SDK_HOME = "collimate-run-sdk"


def sdk_distribution() -> Distribution:
    """Read the ``collimate`` distribution's build-checked metadata, never
    another installation's.

    A source-only script worker imports this package through PYTHONPATH without
    installing its distribution. The resource travels with those same source
    bytes and is generated by the actual wheel metadata constructor.
    """
    root = Path(__file__).parent / '_sdk_metadata'
    path = root / 'METADATA'
    if not path.is_file() or path.is_symlink():
        raise RuntimeError('Canonical SDK runtime metadata is missing')
    distribution = Distribution.at(root)
    if distribution.metadata['Name'] != 'collimate' or not distribution.version:
        raise RuntimeError('Canonical SDK runtime metadata has invalid identity')
    if (not distribution.metadata['Requires-Python']
            or not any('extra ==' not in value for value in distribution.requires or ())):
        raise RuntimeError('Canonical SDK runtime metadata is missing runtime requirements')
    return distribution


def sdk_requirements() -> list[str]:
    """The SDK packages' runtime requirements (:data:`SDK_REQUIREMENTS`),
    each one checked against the distribution's metadata: a requirement the
    distribution does not declare is a stale SDK, never installed on trust."""
    declared = set(sdk_distribution().requires or ())
    missing = [value for value in SDK_REQUIREMENTS if value not in declared]
    if missing:
        raise RuntimeError(f'The SDK requires {", ".join(missing)}, which the collimate metadata does not declare')
    return list(SDK_REQUIREMENTS)
