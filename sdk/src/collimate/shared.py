"""This SDK's own files at runtime: its ``shared/`` tree and its metadata.

The ``shared/`` directory lives at the SDK member's root (beside
``src/``). It holds the authoring how-to docs (``shared/docs/*.md``) — the
canonical, GitHub-browsable source — and is the landing spot for any
cross-cutting, non-Python asset the SDK wants to expose.

Two resolution paths:

1. Installed wheel — ``importlib.resources.files("collimate") / "shared" / ...``.
   Requires ``pyproject.toml`` to force-include ``shared/`` into the
   wheel's package data (``[tool.hatch.build.targets.wheel.force-include]``).

2. In-tree source / editable checkout — fall through to the SDK repo
   root (computed from this file's location) and join ``shared/`` + the
   requested segments.

The returned ``Path`` is always a real filesystem path (the installed
package directory or the checkout); zip / zipimport installs are not
supported — a resource that is not on disk is not found.

:func:`sdk_distribution` reads this SDK source's canonical runtime metadata
(``_sdk_metadata/``), for the generator build and test tooling that stages
the SDK source it runs on.
"""
from __future__ import annotations

import json
from importlib.metadata import Distribution
from importlib.resources import files
from pathlib import Path


_IN_TREE_SDK_ROOT = Path(__file__).resolve().parents[2]


def shared_path(*segments: str) -> Path:
    """Resolve a path inside the SDK's ``shared/`` directory.

    Raises ``FileNotFoundError`` with both attempted locations in the
    message when neither lookup finds the asset.

    Example:
        >>> shared_path("docs", "how-to-write-a-generator.md").read_text()[:20]
        '# How to write a gen'
    """
    rel = "/".join(segments)

    # 1. Installed wheel — importlib.resources.
    try:
        installed = files("collimate").joinpath("shared", *segments)
        if isinstance(installed, Path) and installed.exists():
            return installed
    except (ModuleNotFoundError, FileNotFoundError):
        pass

    # 2. In-tree / editable checkout.
    in_tree = _IN_TREE_SDK_ROOT / "shared" / rel
    if in_tree.exists():
        return in_tree

    raise FileNotFoundError(
        f"Cannot locate shared asset {rel!r}. "
        f"Checked installed package resources (collimate/shared/{rel}) "
        f"and the in-tree path {in_tree}."
    )


def toolchain() -> dict:
    """The toolchain contract, ``shared/contracts/toolchain.json``: the Node
    range every workflow installs (``node``) and the renderer runtime's React
    (``react``, ``react_dom``) with its type packages (``types_react``,
    ``types_react_dom``). The renderer compiler's esbuild is not restated
    there: ``collimate._host.renderer_bundle.CONTRACT["esbuild_version"]``.
    ``scripts/sync_toolchain.py`` writes these values into the npm manifests
    and workflows that cannot read them."""
    return json.loads(shared_path("contracts", "toolchain.json").read_text(encoding="utf-8"))


def sdk_distribution() -> Distribution:
    """Read the package's build-checked metadata, never another installation's.

    A source-only script worker imports this package through PYTHONPATH without
    installing its distribution. The resource travels with those same source
    bytes and is generated by the actual wheel metadata constructor.
    """
    root = Path(__file__).parent / '_sdk_metadata'
    path = root / 'METADATA'
    if not path.is_file() or path.is_symlink():
        raise RuntimeError('Canonical SDK runtime metadata is missing')
    distribution = Distribution.at(root)
    if distribution.metadata['Name'] != 'collimate-sdk' or not distribution.version:
        raise RuntimeError('Canonical SDK runtime metadata has invalid identity')
    if (not distribution.metadata['Requires-Python']
            or not any('extra ==' not in value for value in distribution.requires or ())):
        raise RuntimeError('Canonical SDK runtime metadata is missing runtime requirements')
    return distribution
